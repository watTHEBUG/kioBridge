import { describe, expect, it } from "vitest";
import { DETAIL_OPTIONS, 못채운필수축, 못채운축 } from "./catalog";

/*
 * 이 파일이 지키는 것 — **키오스크가 반드시 골라야 하는 축을 빈 채로 보내지 않는다.**
 *
 * 킷의 통과 조건에 "필수 옵션을 모두 충족" 이 있다. 비면 실행계획이 검증에서
 * 떨어지는데, 그 응답에는 code 도 message 도 없어서 사용자에게 무엇이 빠졌는지
 * 말해 줄 수 없다. 화면이 먼저 막고 이름을 대야 한다.
 *
 * required 값은 킷 5.1.6 의 environments/<환경>/option-groups.json 을 그대로
 * 옮긴 것이다. 여기가 어긋나면 킷과 화면이 다른 말을 하는 것이니, 고칠 때는
 * 킷 파일을 먼저 보라.
 */

const 필수인축 = (place: "음식점" | "병원" | "관공서" | "카페") =>
  DETAIL_OPTIONS[place].filter((o) => o.required).map((o) => o.label);

describe("필수 축 표가 킷과 같다", () => {
  it("닭강정집 — 컵만 선택이다", () => {
    // option-groups.json: SERVICE_TYPE·SPICY_LEVEL·BONE_TYPE·QUANTITY 는 required,
    // CUP 만 required: false 다. 컵을 필수로 만들면 안 골라도 되는 것을 막게 된다.
    expect(필수인축("음식점")).toEqual(["이용 방식", "맵기", "형태", "수량"]);
  });

  it("병원 네 축은 모두 필수다", () => {
    expect(필수인축("병원")).toEqual(["방문 유형", "예약 여부", "진료과", "접근성 지원"]);
  });

  it("관공서 두 축은 모두 필수다", () => {
    expect(필수인축("관공서")).toEqual(["민원 분야", "인증 방식"]);
  });

  it("카페는 필수 축이 없다", () => {
    // 킷에 없는 장소다. 우리가 만든 축이라 필수라고 말할 근거가 없다.
    expect(필수인축("카페")).toEqual([]);
  });
});

describe("못채운필수축", () => {
  it("다 채웠으면 빈 배열이다", () => {
    expect(못채운필수축("음식점", {
      "이용 방식": ["포장하기"], "맵기": ["매운맛"], "형태": ["순살"], "수량": ["2개"],
    })).toEqual([]);
  });

  it("컵은 없어도 주문을 막지 않는다", () => {
    // 킷에서 유일하게 required: false 인 축이다.
    expect(못채운필수축("음식점", {
      "이용 방식": ["포장하기"], "맵기": ["매운맛"], "형태": ["순살"], "수량": ["2개"],
    })).not.toContain("컵");
  });

  it("빠진 축을 화면에 적힌 이름 그대로 돌려준다", () => {
    // 사용자에게 그대로 보여 줄 말이다. 여기서 축 id 를 돌려주면 화면에
    // SPICY_LEVEL 이 뜬다 — P0-1 이 금지한 내부 식별자 노출이다.
    expect(못채운필수축("음식점", { "이용 방식": ["포장하기"], "형태": ["순살"] }))
      .toEqual(["맵기", "수량"]);
  });

  it("빈 배열은 안 고른 것으로 본다", () => {
    // toggleChip 이 다 끄면 축을 빼지만, 예전에 저장한 주문표에는 빈 배열이
    // 남아 있을 수 있다. 있는 척하면 그 주문표가 검증에서 떨어진다.
    expect(못채운필수축("음식점", {
      "이용 방식": [], "맵기": ["매운맛"], "형태": ["순살"], "수량": ["2개"],
    })).toEqual(["이용 방식"]);
  });

  it("장소를 안 골랐으면 볼 축이 없다", () => {
    // 장소 안내가 따로 막는 자리다. 여기서 같이 말하면 두 번 말하게 된다.
    expect(못채운필수축(null, {})).toEqual([]);
  });

  it("selections 가 아예 없어도 던지지 않는다", () => {
    expect(못채운필수축("음식점", undefined)).toEqual(["이용 방식", "맵기", "형태", "수량"]);
  });
});

describe("못채운축 — 저장은 전 축을 요구한다", () => {
  it("필수가 아닌 컵도 저장 기준으로는 빠진 것이다", () => {
    // 킷은 컵을 선택 항목으로 두지만, 반쯤 채운 주문표를 저장해 두면 주문하는
    // 순간에야 빈 칸을 만난다. 저장 화면은 전 축을 요구한다(제품 결정).
    expect(못채운축("음식점", {
      "이용 방식": ["포장하기"], "맵기": ["매운맛"], "형태": ["순살"], "수량": ["2개"],
    })).toEqual(["컵"]);
  });

  it("다 채우면 빈 배열이다", () => {
    expect(못채운축("음식점", {
      "이용 방식": ["포장하기"], "맵기": ["매운맛"], "형태": ["순살"],
      "컵": ["종이컵"], "수량": ["2개"],
    })).toEqual([]);
  });

  it("장소가 없으면 볼 축이 없다", () => {
    expect(못채운축(null, {})).toEqual([]);
  });
});
