/**
 * 이번 이용에서 조건을 **무엇으로 채웠나.**
 *
 * ── 왜 따로 두나 ────────────────────────────────────────────────────────────
 *
 * 계약의 `interaction.preferredInput` 은 사용자가 어떤 방식으로 입력하는 사람인지를
 * 키오스크에 전하는 값이다. 여태 이 값을 `voiceGuide`(소리로 읽어 주기)에서 끌어
 * 왔는데, 그건 **읽어 주는 설정이지 입력 방식이 아니다.** 둘은 자주 어긋난다.
 *
 *   말로 채웠는데 읽어 주기를 껐다   → TOUCH 로 나갔다. 음성으로 넣었는데도.
 *   손으로 골랐는데 읽어 주기를 켰다  → VOICE 로 나갔다. 말한 적 없는데도.
 *
 * 키오스크는 이 값을 보고 안내 방식을 정한다. 틀린 값을 보내면 그쪽이 잘못된
 * 준비를 한다(#99 리뷰).
 *
 * ── 한 번 켜지면 그대로 둔다 ────────────────────────────────────────────────
 *
 * 말로 채운 뒤 손으로 몇 칸 고쳐도 VOICE 다. "이 사람은 말로 넣는 사람" 이라는
 * 사실은 몇 칸 고쳤다고 달라지지 않는다.
 *
 * ── 남기지 않는 것 ──────────────────────────────────────────────────────────
 *
 * 들은 말 자체는 어디에도 안 담는다. 여기 남는 것은 **무엇으로 채웠나** 하는
 * 사실 하나뿐이다(voice.ts 의 들은말 주석).
 */

let 말로채웠나 = false;
/*
 * **말로 들어왔나.** 첫 화면에서 동의를 "네" 로 하거나 "키오브릿지" 라고 부른
 * 사람이다(api/wake.ts).
 *
 * 말로채웠나 와 갈라 둔다. 저것은 '조건을 무엇으로 채웠나' 이고 이것은 '어떻게
 * 들어왔나' 다 — 아직 아무 조건도 안 채운 시점에 이미 알 수 있는 사실이라,
 * 뒤따르는 화면이 그에 맞게 열릴 수 있다.
 *
 * 소리 안내가 켜졌는지로는 이걸 알 수 없다. 그 스위치는 이제 기본이 켜짐이라
 * 모든 사람이 참이고, 그걸로 문을 열면 눈으로 보는 분의 마이크까지 열린다.
 * 말로 들어왔다는 것은 **그 사람이 실제로 말을 한** 사실이다.
 *
 * 새로고침 너머로는 안 남긴다. 남길 값어치가 있는 것은 계약으로 나가는
 * 말로채웠나 뿐이고, 이 값은 그 흐름 안에서만 쓰인다 — 새로고침해서 첫 화면으로
 * 돌아가면 거기서 다시 말로 들어오면 된다.
 */
let 말로들어왔나 = false;
const 듣는이 = new Set<() => void>();

const 알리기 = () => { for (const f of 듣는이) f(); };

export const 입력출처 = {
  /** 이번 이용에서 말로 채운 적이 있나. */
  말로채운적있나: (): boolean => 말로채웠나,

  /** 첫 화면을 말로 지나온 사람인가. 뒤 화면이 말하기를 먼저 열지 정한다. */
  말로들어온적있나: (): boolean => 말로들어왔나,

  /** 동의를 "네" 로 받았거나 부르는 말이 들렸을 때 부른다(첫 화면). */
  말로들어옴(): void {
    if (말로들어왔나) return;
    말로들어왔나 = true;
    알리기();
  },

  /** 말로 채웠다고 표시한다. 확인 화면에서 '이대로 채우기' 를 누른 뒤에 부른다. */
  말로채움(): void {
    if (말로채웠나) return;
    말로채웠나 = true;
    알리기();
  },

  /** 로그아웃·기기 지우기에서 부른다. 다음 사람에게 앞사람의 방식이 이어지면 안 된다. */
  비우기(): void {
    if (!말로채웠나 && !말로들어왔나) return;
    말로채웠나 = false;
    말로들어왔나 = false;
    알리기();
  },

  /** 새로고침 뒤에 되돌린다. 되살리는 것은 알리지 않는다 — 그리는 중에 부르기 때문이다. */
  되살리기(v: boolean): void {
    말로채웠나 = v;
  },

  구독(f: () => void): () => void {
    듣는이.add(f);
    return () => { 듣는이.delete(f); };
  },
};
