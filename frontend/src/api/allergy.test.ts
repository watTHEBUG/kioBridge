import { beforeEach, describe, expect, it } from "vitest";
import { 알레르기목록, 알레르기설정, 아는알레르기 } from "@/api/allergy";

// 모듈 저장소라 시험 사이에 값이 남는다. 앞 시험이 켜 둔 것이 다음 시험으로
// 흘러가면 무엇 때문에 통과했는지 알 수 없다(backend.test.ts 의 같은 자리와 같은 이유).
beforeEach(() => 알레르기설정.비우기());

/*
 * 이 파일이 지키는 것.
 *
 * "알레르기가 없다" 와 "아직 답이 없다" 는 다르다. 값만 보면 둘 다 빈 배열이라
 * 갈릴 수가 없고, 갈리지 않으면 설정 화면이 답을 받고 넘어갈 방법이 없다.
 *
 * 서버로 나가는 값은 이 변경으로 **안 바뀐다** — 고른 것이 있으면 그 목록,
 * '없음' 이면 빈 배열이다. 답했다는 표는 화면이 쓰는 값이다.
 */
describe("답했는가 — '없다' 와 '아직 답이 없다' 는 다르다", () => {
  it("처음에는 답한 적이 없다", () => {
    expect(알레르기설정.답했나()).toBe(false);
    expect(알레르기설정.읽기()).toEqual([]);
  });

  it("'없음' 은 값을 안 넣지만 답한 것이다", () => {
    알레르기설정.없음으로();
    expect(알레르기설정.읽기()).toEqual([]);
    expect(알레르기설정.답했나()).toBe(true);
  });

  it("하나 고르면 답한 것이다", () => {
    알레르기설정.뒤집기("PEANUT");
    expect(알레르기설정.읽기()).toEqual(["PEANUT"]);
    expect(알레르기설정.답했나()).toBe(true);
  });

  it("골랐다 도로 꺼도 답한 사실은 남는다", () => {
    // 켰다 껐다는 것은 이 칸을 보고 판단했다는 뜻이다. 다시 물으면 같은 답을 두 번 받는다.
    알레르기설정.뒤집기("PEANUT");
    알레르기설정.뒤집기("PEANUT");
    expect(알레르기설정.읽기()).toEqual([]);
    expect(알레르기설정.답했나()).toBe(true);
  });

  it("'없음' 뒤에 하나를 고르면 값이 들어간다", () => {
    // 화면에서 '없음' 칩은 고른 것이 비었을 때만 켜지므로, 이 순간 저절로 꺼진다.
    알레르기설정.없음으로();
    알레르기설정.뒤집기("MILK");
    expect(알레르기설정.읽기()).toEqual(["MILK"]);
    expect(알레르기설정.답했나()).toBe(true);
  });

  it("비우기는 답한 사실까지 지운다 — 로그아웃·초기화가 쓴다", () => {
    알레르기설정.없음으로();
    알레르기설정.비우기();
    expect(알레르기설정.답했나()).toBe(false);
  });
});

describe("되살릴 때", () => {
  it("고른 것이 있으면 답한 것으로 본다", () => {
    /*
     * 표를 안 들고 오는 길이 있다 — 계정 프로필에는 allergies 만 있다(팀 계약).
     * 값이 있는데 답을 안 한 것으로 두면 이미 골라 둔 사람에게 설정 화면이 다시 막힌다.
     */
    알레르기설정.되살리기(["PEANUT"]);
    expect(알레르기설정.답했나()).toBe(true);
  });

  it("비어 있으면 표를 따른다", () => {
    알레르기설정.되살리기([], true);
    expect(알레르기설정.답했나()).toBe(true);
    알레르기설정.되살리기([], undefined);
    expect(알레르기설정.답했나()).toBe(false);
  });

  it("교체도 같은 규칙이다", () => {
    알레르기설정.교체([], true);
    expect(알레르기설정.답했나()).toBe(true);
    expect(알레르기설정.읽기()).toEqual([]);
  });
});

describe("받는 값을 가린다", () => {
  it("목록에 없는 값은 안 받는다", () => {
    알레르기설정.되살리기(["PEANUT", "메밀", "UNKNOWN", 1, null, "SHRIMP"]);
    expect(알레르기설정.읽기()).toEqual(["PEANUT", "SHRIMP"]);
  });

  it("배열이 아니면 빈 것으로 본다", () => {
    알레르기설정.되살리기("PEANUT");
    expect(알레르기설정.읽기()).toEqual([]);
  });

  it("목록 순서로 세운다 — 손댄 순서가 화면 순서를 흔들지 않게", () => {
    알레르기설정.되살리기(["SHRIMP", "PEANUT"]);
    expect(알레르기설정.읽기()).toEqual(["PEANUT", "SHRIMP"]);
  });

  it("아는알레르기 는 킷이 아는 여섯만 참이다", () => {
    expect(알레르기목록).toHaveLength(6);
    for (const { id } of 알레르기목록) expect(아는알레르기(id)).toBe(true);
    // UNKNOWN 도 거짓이다 — 계약에는 있지만 화면에서 고를 수 있는 값이 아니다.
    for (const v of ["UNKNOWN", "메밀", "", 1, null, undefined]) expect(아는알레르기(v)).toBe(false);
  });
});

describe("구독", () => {
  it("'없음' 도 값 바뀜으로 알린다", () => {
    // 안 알리면 화면이 '없음' 칩을 켜 주지 못하고, '계속하기' 도 잠긴 채로 남는다.
    let 횟수 = 0;
    const 끊기 = 알레르기설정.구독(() => { 횟수 += 1; });
    알레르기설정.없음으로();
    알레르기설정.뒤집기("EGG");
    끊기();
    알레르기설정.없음으로();
    expect(횟수).toBe(2);
  });

  it("되살리기는 안 알린다 — 첫 그림 전에 부르는 값이다", () => {
    let 횟수 = 0;
    const 끊기 = 알레르기설정.구독(() => { 횟수 += 1; });
    알레르기설정.되살리기(["PEANUT"], true);
    끊기();
    expect(횟수).toBe(0);
  });
});
