import { type AllergenId } from "@/api/canonical";

/**
 * 이 사람이 늘 피해야 하는 것.
 *
 * 주문표에도 알레르기 축이 있는데 왜 따로 두나 —
 * **알레르기는 주문마다 달라지는 값이 아니라 그 사람에 대한 사실**이기 때문이다.
 * 주문표에만 두면 새 주문표를 만들 때마다 다시 골라야 하고, 한 번 빠뜨리면
 * 그 주문표로 주문할 때 걸러지지 않는다. 빠뜨려도 되는 값이 아니다.
 *
 * ── 주문표 쪽과 합친다, 덮지 않는다 ─────────────────────────────────────────
 *
 * 서버로 나갈 때 주문표의 알레르기와 **합집합**을 만든다(canonical.ts).
 * 합치면 걸러지는 후보가 늘어날 뿐 줄지 않는다 — 어느 쪽을 빠뜨려도 안전한
 * 방향으로만 틀린다. 덮어쓰면 한쪽이 사라져서 안 걸러진다.
 *
 * ── 여섯뿐인 이유 ──────────────────────────────────────────────────────────
 *
 * 킷 계약의 AllergenId 가 여섯에 UNKNOWN 하나다. 표에 없는 것을 고르게 하면
 * UNKNOWN 으로 나가고, 서버는 그걸 '확인 못 한 절대 조건' 으로 보고 주문을
 * 아예 막는다(RECONFIRMATION_REQUIRED). 고를 수 있게 해 놓고 고르면 주문이
 * 안 되는 칸을 만들지 않는다.
 *
 * ── 그래서 '없음' 이 필요하다 ──────────────────────────────────────────────
 *
 * 여섯 중에 해당하는 것이 없는 분이 대부분이다. 그분들에게 "아무것도 안 누르기"
 * 를 답으로 쓰게 하면, 앱은 그 사람이 답한 것인지 이 칸을 못 보고 지나간 것인지
 * 알 수 없다. '없음' 은 그 답을 받는 자리다(아래 답함).
 */

export const 알레르기목록: { id: AllergenId; label: string }[] = [
  { id: "PEANUT", label: "땅콩" },
  { id: "SOY", label: "대두" },
  { id: "MILK", label: "우유" },
  { id: "EGG", label: "계란" },
  { id: "WHEAT", label: "밀" },
  { id: "SHRIMP", label: "새우" },
];

const 아는것 = new Set<string>(알레르기목록.map((x) => x.id));

/** 저장된 값이 우리가 아는 알레르기인가. 모르는 값은 받지 않는다. */
export const 아는알레르기 = (v: unknown): v is AllergenId =>
  typeof v === "string" && 아는것.has(v);

let 값: AllergenId[] = [];
/*
 * 이 물음에 답을 했는가. **'없다' 와 '아직 답이 없다' 는 다르다.**
 *
 * 값이 빈 배열이면 그만이던 때가 있었다. 그러면 "없어요" 라고 답한 사람과 아직
 * 답하지 않은 사람이 앱에게 똑같아진다 — 알레르기는 빠뜨려도 되는 값이 아니라서,
 * 둘을 갈라야 "답을 받고 나서 넘어간다" 는 문을 만들 수 있다.
 *
 * ── 서버에 기대지 않는다 ────────────────────────────────────────────────────
 *
 * 이 표는 **서버로 안 나간다.** 나가는 값(allergenIds)은 예전과 똑같다 —
 * 고른 것이 있으면 그 목록, '없음' 이면 빈 배열이다. 계약은 한 글자도 안 바뀐다.
 *
 * 서버가 막아 주기를 기다리지 않는 이유 — 킷은 빈 배열을 정상적인 답으로 본다
 * (RuleEvaluatorImpl 의 absentMeans="NONE" → SKIPPED). 안 고른 것을 서버가
 * 걸러 주지 않으니, 애초에 답 없이 서버까지 가지 못하게 화면에서 막는다.
 * 막는 자리도 그쪽이 낫다 — 주문 승인 직전이 아니라 설정 화면이다.
 */
let 답함 = false;
const 듣는이 = new Set<() => void>();

export const 알레르기설정 = {
  읽기: (): AllergenId[] => 값,
  /** 이 물음에 답했는가('없음' 포함). 설정 화면이 다음으로 넘어갈지 이 값으로 정한다. */
  답했나: (): boolean => 답함,
  /** 하나를 켜고 끈다. 목록 순서를 지켜서 화면과 서버로 나가는 순서가 같게 둔다. */
  뒤집기(id: AllergenId): void {
    const 있음 = 값.includes(id);
    값 = 알레르기목록
      .map((x) => x.id)
      .filter((x) => (x === id ? !있음 : 값.includes(x)));
    // 하나라도 손을 댔으면 답한 것이다. 다시 다 끄더라도 답한 사실은 남는다 —
    // 켰다 껐다는 것은 이 칸을 보고 판단했다는 뜻이다.
    답함 = true;
    for (const f of 듣는이) f();
  },
  /** '없음' 을 고른다. 값은 비우되 **답한 것으로 남긴다.** */
  없음으로(): void {
    값 = [];
    답함 = true;
    for (const f of 듣는이) f();
  },
  /** 처음으로 되돌린다. 답한 사실까지 지운다 — 로그아웃·초기화가 쓴다. */
  비우기(): void {
    값 = [];
    답함 = false;
    for (const f of 듣는이) f();
  },
  /**
   * 저장해 둔 값으로 되돌린다. **듣는이에게 알리지 않는다.**
   * 화면이 첫 그림을 그리기 전에 한 번만 부른다 — a11y.ts 의 되살리기 와 같은 이유다.
   */
  되살리기(목록: unknown, 답한적있나?: unknown): void {
    const 받은것 = Array.isArray(목록) ? 목록.filter(아는알레르기) : [];
    // 목록 순서로 정리한다. 손댄 순서가 화면 순서를 흔들지 않게.
    값 = 알레르기목록.map((x) => x.id).filter((id) => 받은것.includes(id));
    /*
     * 고른 것이 하나라도 있으면 답한 것으로 본다.
     *
     * 표를 안 들고 오는 길이 있어서다 — 계정 프로필에는 allergies 만 있고(팀 계약),
     * 표는 이 기기의 이어쓰기에만 있다. 값이 있는데 답을 안 한 것으로 두면
     * 이미 골라 둔 사람에게 설정 화면이 다시 막힌다.
     */
    답함 = 답한적있나 === true || 값.length > 0;
  },
  /**
   * 서버에서 받은 값으로 바꾼다. 되살리기 와 달리 **알린다.**
   *
   * 로그인은 첫 그림이 그려진 뒤에 일어난다. 안 알리면 열려 있던 알레르기
   * 화면이 옛 값을 그대로 보여 주고, 사용자는 계정 값이 적용된 줄 모른다.
   */
  교체(목록: unknown, 답한적있나?: unknown): void {
    this.되살리기(목록, 답한적있나);
    for (const f of 듣는이) f();
  },
  구독(f: () => void): () => void {
    듣는이.add(f);
    return () => { 듣는이.delete(f); };
  },
};
