import { 개인정보같은글 } from "@/api/account";
import { 연동기록, 팀백엔드모드 } from "@/api/devlog";

/**
 * 말한 맵기를 서버가 골라 준다(팀 #133).
 *
 * ── 왜 서버가 필요한가 ───────────────────────────────────────────────────────
 *
 * 지금 말 맞추기(voice.ts)는 **화면에 떠 있는 보기와 글자를 대조**한다. 그래서
 * "매운맛"·"안 맵게" 처럼 표에 적어 둔 말은 잡지만, "불닭맛"·"얼큰한맛" 처럼
 * 표에 없는 말은 못 잡는다. 사람이 실제로 쓰는 말은 훨씬 많고, 그걸 전부
 * 앞에 적어 두는 것은 끝이 없다.
 *
 * 서버는 앵커 표현과의 임베딩 유사도로 고른다. 표에 없던 말도 잡는다.
 *
 * ── 부정은 서버가 읽는다 ────────────────────────────────────────────────────
 *
 * 한동안 여기에 겹이 하나 더 있었다. 유사도가 부정을 못 읽던 때 —
 * "안 매운 거" 안에 "매운" 이 들어 있어 매운맛 앵커와 가깝다고 봤다(실측:
 * confident=true, HOT) — 우리 쪽 부정 표로 서버 답을 다시 거르던 방어다.
 *
 * 팀 #138 이 서버에 부정어 필터를 넣어 고쳤다. 배포본으로 확인한 뒤 그 겹을
 * 걷어냈다. 같은 판단을 두 곳에서 하면, 어긋났을 때 어느 쪽이 옳은지 알기
 * 어려워진다. 판단은 서버 한 곳에서 한다.
 *
 * 그 대신 **서버가 되돌아가면 이 앱은 그대로 따라간다.** 시험으로는 못 잡는다 —
 * 시험은 fetch 를 흉내 내므로 서버가 무엇을 답하든 초록이다. 배포 뒤에 실서버로
 * 한 번 물어보는 수밖에 없다(방법은 spicy.test.ts 의 curl 에 적어 뒀다).
 *
 * ── 실패하면 조용히 물러난다 ─────────────────────────────────────────────────
 *
 * 이 경로가 없어도 앱은 지금처럼 동작한다(손으로 고르기). 서버가 없거나
 * 느리거나 프로필이 안 켜져 있으면 못함 을 돌려주고, 화면은 원래 하던 대로
 * "못 골랐어요" 로 간다. 음성은 편의지 이 앱이 하는 일이 아니다.
 */

/** 서버가 쓰는 enum 과 화면 칩 이름. 화면에 없는 말을 사용자에게 들려주지 않는다. */
const 칩이름: Record<string, string> = {
  HOT: "매운맛",
  MEDIUM: "보통맛",
  MILD: "순한맛",
  NO_PREFERENCE: "상관없음",
};

export type 맵기결과 =
  /** 확정. 화면 칩 이름이다. */
  | { 고른값: string }
  /** 애매하다. 이 중에서 되물어야 한다. 화면 칩 이름들이다. */
  | { 되물을것: string[] }
  /** 못 골랐다(서버 없음·오류·부정 걸림). 화면은 원래 하던 대로 간다. */
  | { 못함: true };

/**
 * 서버가 준 enum 목록을 화면 칩 이름으로. 화면에 없는 이름은 뺀다.
 *
 * 몇 개가 빠졌는지는 이제 안 센다. 예전에는 셌다 — 후보가 하나만 남으면 그것을
 * 확정으로 삼았기 때문에, 우리가 버려서 하나가 된 것인지 원래 하나였는지를
 * 갈라야 했다. 지금은 **확신 못 한 답은 개수와 상관없이 늘 되묻는다**(아래).
 * 그래서 그 구분이 필요 없어졌다.
 */
const 이름으로 = (값들: unknown): string[] => {
  if (!Array.isArray(값들)) return [];
  return 값들
    .filter((v): v is string => typeof v === "string")
    .map((v) => 칩이름[v])
    .filter(Boolean);
};

/**
 * 서버가 이만큼 안에 답하지 않으면 포기한다.
 *
 * 없으면 화면이 '인식 중…' 에 머문 채 말하기 단추가 계속 잠겨 있다. 사용자는
 * 무엇을 기다리는지도 모르고 손으로 고를 수도 없다 — 안 되는 것보다 나쁘다.
 * 임베딩 한 번은 보통 1초 안쪽이고, BFF 도 15초에 끊는다.
 */
const 기다릴시간 = 8000;

export const 맵기물어보기 = async (들은말: string): Promise<맵기결과> => {
  const 글 = 들은말.replace(/\s+/g, " ").trim();
  // 서버가 @Size(max = 100) 을 걸어 두었다. 넘겨 봐야 400 이라 여기서 접는다.
  if (글 === "" || 글.length > 100) return { 못함: true };

  /*
   * 개인정보처럼 보이는 말은 **보내지 않는다.**
   *
   * 여기 오는 것은 보기와도 예/아니오와도 안 맞은 말이라, 사람이 무슨 말을
   * 했는지 알 수 없다. 전화번호나 주소를 말했으면 그 말이 우리 BFF 를 지나
   * 백엔드를 거쳐 OpenAI 까지 간다. 이 앱은 실제 개인정보를 받지도 저장하지도
   * 않는다고 화면에서 약속하고 있다.
   *
   * 메모·메뉴 이름에 쓰는 것과 같은 가드를 쓴다(account.ts). 말로 들어오는
   * 길만 예외로 두면 막아 둔 뜻이 없다.
   */
  if (개인정보같은글(글)) return { 못함: true };

  /*
   * 기록에 남기는 경로는 앞의 `/api/bff` 를 **뗀 모양**이다.
   *
   * createTeamBackend 가 그렇게 남기고(backend.ts 의 적기), 개발 패널의 경로표가
   * startsWith 로 설명을 찾는다. 여기만 붙여서 남기면 그 표에 안 걸려 이름도
   * 설명도 없는 줄로 뜬다 — 실제로 그랬고, 그래서 "맵기 호출이 안 뜬다" 로 보였다.
   */
  const 경로 = "/internal/spicy-level/match";
  const 부를곳 = "/api/bff" + 경로;
  const 시작 = 팀백엔드모드 ? performance.now() : 0;
  const 보낼본문 = JSON.stringify({ text: 글 });
  /*
   * 오간 것에 남긴다. 여태 이 호출만 기록을 안 탔다 — 개발 패널을 보면서
   * 맵기를 말해도 아무 줄도 안 떠서, 서버에 붙은 것인지 아닌지 알 수 없었다.
   * createTeamBackend 를 거치지 않고 직접 부르는 자리라 빠져 있었다.
   *
   * ── 본문까지 남긴다. 그리고 그게 무슨 뜻인지 ────────────────────────────
   *
   * 이 기록을 연동 자료로 쓰기로 해서 요청·응답을 그대로 남긴다. 경로와 상태만
   * 있으면 "요청이 나갔다" 는 알 수 있어도 "이 판정이 서버에서 온 것이다" 는
   * 못 보인다 — 자료로 쓸 값어치가 거기 있다고 보았다.
   *
   * 그런데 그 값이 곧 **사용자가 말한 문장**이다. 요청의 text 와 응답의
   * heardText 가 그것이고, 이 패널은 배포본에서도 보인다(build:team). 이름이나
   * 전화번호를 말하면 시연 화면과 녹화에 그대로 찍힌다.
   *
   * 이 앱은 실제 개인정보를 받지도 저장하지도 않는다고 화면에서 약속한다.
   * 이 경로는 애초에 **보기와도 예/아니오와도 안 맞은 말**이 오는 자리라
   * 무슨 말이 들어올지 모른다 — 그래서 위에서 개인정보처럼 보이는 말을 아예
   * 안 보내고 있다. 그 문을 만들어 놓고 기록에 남기면 뜻이 없다.
   *
   * 무엇이 오갔는지는 경로와 상태로 충분하다.
   */
  const 적기 = (상태: number | "실패", 응답본문?: string) => {
    if (!팀백엔드모드) return;
    연동기록.남기기({
      방법: "POST", 경로, 상태,
      걸린시간: Math.round(performance.now() - 시작), 시각: Date.now(),
      요청: 보낼본문,
      ...(응답본문 === undefined ? {} : { 응답: 응답본문 }),
    });
  };

  const 시계 = new AbortController();
  const 타이머 = setTimeout(() => 시계.abort(), 기다릴시간);
  let res: Response;
  try {
    res = await fetch(부를곳, {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: 보낼본문,
      signal: 시계.signal,
    });
  } catch {
    // 끊겼든 시간이 다 됐든 사용자가 할 일은 같다 — 손으로 고른다.
    적기("실패");
    return { 못함: true };
  } finally {
    clearTimeout(타이머);
  }

  /*
   * 글로 먼저 읽고 그것을 기록에 남긴 뒤에 해석한다.
   *
   * res.json() 을 바로 부르면 본문을 한 번밖에 못 읽어서 기록에 남길 것이
   * 없어진다. 해석에 실패해도 무엇이 왔는지는 보여야 한다 — 자료로 쓸 때
   * 정작 필요한 것이 그 '이상한 응답' 이다.
   */
  const 받은글 = await res.text().catch(() => "");
  적기(res.status, 받은글);
  if (!res.ok) return { 못함: true };

  let 본문: { confident?: boolean; matchedLevel?: string; candidates?: unknown } | null = null;
  try { 본문 = 받은글 ? JSON.parse(받은글) : null; } catch { 본문 = null; }
  if (!본문) return { 못함: true };

  const 후보 = 이름으로(본문.candidates);

  if (본문.confident === true && typeof 본문.matchedLevel === "string") {
    const 이름 = 칩이름[본문.matchedLevel];
    // 화면에 없는 이름이면 사용자에게 내밀 수 없다. 손으로 고르게 둔다.
    return 이름 ? { 고른값: 이름 } : { 못함: true };
  }

  /*
   * 여기부터는 서버가 **확신하지 못한** 답이다. 하나만 남아도 우리가 고르지
   * 않는다.
   *
   * 예전에는 후보가 하나면 그것을 확정으로 삼았다. 그런데 서버는 확신하지
   * 못할 때 되물을 문장(clarificationQuestion)까지 같이 보낸다 — 그쪽도 묻고
   * 싶다는 뜻이다. 그걸 우리가 대신 골라 버리면 안 된다.
   *
   * #138 전에 실제로 그랬다. "하나도 안 맵게" 에 confident=false 이면서
   * candidates 가 ["NO_PREFERENCE"] 하나뿐이었고, 우리는 그것을 자동으로
   * 골랐다 — 맵기를 못 드셔서 그렇게 말한 분의 주문이 물어본 적도 없이
   * '상관없음' 으로 넘어갔다. (지금 서버는 같은 말에 ["MILD","MEDIUM"] 을
   * 준다. 고쳐졌지만, 규칙은 후보 개수가 아니라 confident 에 걸어 둔다.)
   *
   * 부정어 방어를 걷어낸 지금은 이 겹이 더 중요하다 — 예전에는 우리 부정어 표에
   * 걸리면 되물음으로 내려가는 길이 하나 더 있었지만, 이제 없다.
   */
  if (후보.length === 0) return { 못함: true };
  return { 되물을것: 후보 };
};
