import { 개인정보같은글 } from "@/api/account";

/**
 * 말한 맵기를 서버가 골라 준다(팀 #133).
 *
 * ── 왜 서버가 필요한가 ───────────────────────────────────────────────────────
 *
 * 지금 말 맞추기(voice.ts)는 **화면에 떠 있는 보기와 글자를 대조**한다. 그래서
 * "매운맛"·"안 맵게" 처럼 표에 적어 둔 말은 잡지만, "불닭맛"·"얼큰한맛" 처럼
 * 표에 없는 말은 못 잡는다. 사람이 실제로 쓰는 말은 훨씬 많고, 그걸 전부
 * 앞에 적어 두는 것은 끝이 없다.
 *
 * 서버는 앵커 표현과의 임베딩 유사도로 고른다. 표에 없던 말도 잡는다.
 *
 * ── 부정은 서버가 읽는다 ────────────────────────────────────────────────────
 *
 * 한동안 여기에 겹이 하나 더 있었다. 유사도가 부정을 못 읽던 때 —
 * "안 매운 거" 안에 "매운" 이 들어 있어 매운맛 앵커와 가깝다고 봤다(실측:
 * confident=true, HOT) — 우리 쪽 부정 표로 서버 답을 다시 거르던 방어다.
 *
 * 팀 #138 이 서버에 부정어 필터를 넣어 고쳤다. 배포본으로 확인한 뒤 그 겹을
 * 걷어냈다. 같은 판단을 두 곳에서 하면, 어긋났을 때 어느 쪽이 옳은지 알기
 * 어려워진다. 판단은 서버 한 곳에서 한다.
 *
 * 그 대신 **서버가 되돌아가면 이 앱은 그대로 따라간다.** 시험으로는 못 잡는다 —
 * 시험은 fetch 를 흉내 내므로 서버가 무엇을 답하든 초록이다. 배포 뒤에 실서버로
 * 한 번 물어보는 수밖에 없다(방법은 spicy.test.ts 의 curl 에 적어 뒀다).
 *
 * ── 실패하면 조용히 물러난다 ─────────────────────────────────────────────────
 *
 * 이 경로가 없어도 앱은 지금처럼 동작한다(손으로 고르기). 서버가 없거나
 * 느리거나 프로필이 안 켜져 있으면 못함 을 돌려주고, 화면은 원래 하던 대로
 * "못 골랐어요" 로 간다. 음성은 편의지 이 앱이 하는 일이 아니다.
 */

/** 서버가 쓰는 enum 과 화면 칩 이름. 화면에 없는 말을 사용자에게 들려주지 않는다. */
const 칩이름: Record<string, string> = {
  HOT: "매운맛",
  MEDIUM: "보통맛",
  MILD: "순한맛",
  NO_PREFERENCE: "상관없음",
};

export type 맵기결과 =
  /** 확정. 화면 칩 이름이다. */
  | { 고른값: string }
  /** 애매하다. 이 중에서 되물어야 한다. 화면 칩 이름들이다. */
  | { 되물을것: string[] }
  /** 못 골랐다(서버 없음·오류·부정 걸림). 화면은 원래 하던 대로 간다. */
  | { 못함: true };

/**
 * 서버가 준 enum 목록을 화면 칩 이름으로.
 *
 * 모르는 값이 있었는지도 같이 돌려준다. 그걸 조용히 버리면 **서버의 '모르겠다'
 * 가 우리 쪽에서 '확정' 으로 바뀐다** — 서버가 [MEDIUM, EXTRA_HOT] 을 놓고
 * 확신 못 한다고 했는데, 우리가 EXTRA_HOT 을 버리면 보통맛 하나만 남아서
 * 마치 정해진 것처럼 보인다. 서버가 망설인 것을 우리가 없앨 수는 없다.
 */
const 이름으로 = (값들: unknown): { 이름들: string[]; 모르는것있나: boolean } => {
  if (!Array.isArray(값들)) return { 이름들: [], 모르는것있나: false };
  const 글자만 = 값들.filter((v): v is string => typeof v === "string");
  const 이름들 = 글자만.map((v) => 칩이름[v]).filter(Boolean);
  return { 이름들, 모르는것있나: 이름들.length !== 글자만.length };
};

/**
 * 서버가 이만큼 안에 답하지 않으면 포기한다.
 *
 * 없으면 화면이 '인식 중…' 에 머문 채 말하기 단추가 계속 잠겨 있다. 사용자는
 * 무엇을 기다리는지도 모르고 손으로 고를 수도 없다 — 안 되는 것보다 나쁘다.
 * 임베딩 한 번은 보통 1초 안쪽이고, BFF 도 15초에 끊는다.
 */
const 기다릴시간 = 8000;

export const 맵기물어보기 = async (들은말: string): Promise<맵기결과> => {
  const 글 = 들은말.replace(/\s+/g, " ").trim();
  // 서버가 @Size(max = 100) 을 걸어 두었다. 넘겨 봐야 400 이라 여기서 접는다.
  if (글 === "" || 글.length > 100) return { 못함: true };

  /*
   * 개인정보처럼 보이는 말은 **보내지 않는다.**
   *
   * 여기 오는 것은 보기와도 예/아니오와도 안 맞은 말이라, 사람이 무슨 말을
   * 했는지 알 수 없다. 전화번호나 주소를 말했으면 그 말이 우리 BFF 를 지나
   * 백엔드를 거쳐 OpenAI 까지 간다. 이 앱은 실제 개인정보를 받지도 저장하지도
   * 않는다고 화면에서 약속하고 있다.
   *
   * 메모·메뉴 이름에 쓰는 것과 같은 가드를 쓴다(account.ts). 말로 들어오는
   * 길만 예외로 두면 막아 둔 뜻이 없다.
   */
  if (개인정보같은글(글)) return { 못함: true };

  const 시계 = new AbortController();
  const 타이머 = setTimeout(() => 시계.abort(), 기다릴시간);
  let res: Response;
  try {
    res = await fetch("/api/bff/internal/spicy-level/match", {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({ text: 글 }),
      signal: 시계.signal,
    });
  } catch {
    // 끊겼든 시간이 다 됐든 사용자가 할 일은 같다 — 손으로 고른다.
    return { 못함: true };
  } finally {
    clearTimeout(타이머);
  }
  if (!res.ok) return { 못함: true };

  const 본문 = await res.json().catch(() => null) as
    { confident?: boolean; matchedLevel?: string; candidates?: unknown } | null;
  if (!본문) return { 못함: true };

  const { 이름들: 후보, 모르는것있나 } = 이름으로(본문.candidates);

  if (본문.confident === true && typeof 본문.matchedLevel === "string") {
    const 이름 = 칩이름[본문.matchedLevel];
    // 화면에 없는 이름이면 사용자에게 내밀 수 없다. 손으로 고르게 둔다.
    return 이름 ? { 고른값: 이름 } : { 못함: true };
  }

  if (후보.length === 0) return { 못함: true };
  if (후보.length === 1 && !모르는것있나) return { 고른값: 후보[0] };
  return { 되물을것: 후보 };
};
