import { afterEach, describe, expect, it } from "vitest";
import { 입력출처 } from "./inputsource";

/*
 * 이 파일이 지키는 것.
 *
 *   ① 말로 채운 것과 말로 들어온 것은 **다른 사실**이다. 하나로 묶으면, 아직
 *      아무 조건도 안 채운 사람을 '말로 채운 사람' 으로 계약에 실어 보낸다.
 *   ② 지우면 둘 다 지워진다. 다음 사람에게 앞사람의 방식이 이어지면 안 된다.
 */

afterEach(() => 입력출처.비우기());

describe("말로 채운 것과 말로 들어온 것", () => {
  it("말로 들어와도 '말로 채웠다' 가 되지는 않는다", () => {
    /*
     * 말로채운적있나 는 계약의 preferredInput 으로 나간다(backend.ts). 첫 화면을
     * 말로 지나왔을 뿐 아직 조건은 하나도 안 채운 사람을 VOICE 로 보내면,
     * 키오스크가 그 사람이 하지도 않은 입력 방식에 맞춰 준비한다.
     */
    입력출처.말로들어옴();
    expect(입력출처.말로들어온적있나()).toBe(true);
    expect(입력출처.말로채운적있나()).toBe(false);
  });

  it("말로 채워도 '말로 들어왔다' 가 되지는 않는다", () => {
    // 손으로 시작해 놓고 한 칸만 말로 채운 사람이다. 뒤 화면을 우리가 열지 않는다.
    입력출처.말로채움();
    expect(입력출처.말로채운적있나()).toBe(true);
    expect(입력출처.말로들어온적있나()).toBe(false);
  });

  it("한 번 켜지면 그대로다", () => {
    입력출처.말로들어옴();
    입력출처.말로들어옴();
    expect(입력출처.말로들어온적있나()).toBe(true);
  });
});

describe("지우면 둘 다 지워진다", () => {
  it("앞사람의 방식이 다음 사람에게 안 이어진다", () => {
    입력출처.말로채움();
    입력출처.말로들어옴();
    입력출처.비우기();
    expect(입력출처.말로채운적있나()).toBe(false);
    expect(입력출처.말로들어온적있나()).toBe(false);
  });

  it("하나만 켜져 있어도 지운다", () => {
    // 비우기 가 이른 반환으로 빠지면, 남은 한쪽이 다음 사람에게 이어진다.
    입력출처.말로들어옴();
    입력출처.비우기();
    expect(입력출처.말로들어온적있나()).toBe(false);
  });
});

describe("구독", () => {
  it("말로 들어옴도 듣는이에게 알린다", () => {
    let 불림 = 0;
    const 끊기 = 입력출처.구독(() => { 불림 += 1; });
    입력출처.말로들어옴();
    expect(불림).toBe(1);
    끊기();
  });
});
