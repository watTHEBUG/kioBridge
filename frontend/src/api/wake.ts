/**
 * 부르는 말을 기다린다. 손을 한 번도 안 대고 시작하기 위한 문.
 *
 * ── 왜 필요한가 ─────────────────────────────────────────────────────────────
 *
 * 이어 듣기(api/vad.ts)로 답하는 동안은 손을 안 대게 됐다. 그런데 **맨 처음
 * 한 번**은 여전히 '말하기' 를 눌러야 시작한다. 화면을 못 보는 분에게는 그
 * 한 번이 남은 장벽이다 — 어디를 눌러야 하는지 찾는 일이 문제이지, 누르는
 * 일이 문제가 아니다.
 *
 * ── 평소에는 아무것도 안 보낸다 ─────────────────────────────────────────────
 *
 * 상시 대기는 **기기 안에서만** 돈다. vad 가 소리의 크기만 재고 있다가, 사람이
 * 실제로 말한 뒤 조용해진 순간에만 그 한 토막을 서버로 보내 무슨 말이었는지
 * 묻는다(들어보기 의 스스로끝내기). 조용한 동안에는 한 바이트도 안 나간다.
 *
 * 그러니 "웨이크워드 인식을 기기 안에서 한다" 는 말은 아니다. **기다리는 일**이
 * 기기 안에서 돌고, 말이 났을 때만 그 말이 무엇인지를 서버에 묻는다. 이 앱은
 * 못 하는 것을 한다고 말하지 않는다 — 화면 안내도 그렇게 적는다.
 *
 * ── 끝없이 돌지 않는다 ──────────────────────────────────────────────────────
 *
 * 기다리기는 공짜가 아니다. 마이크가 켜져 있고, 누가 말할 때마다 인식 호출이
 * 하나씩 나간다. 옆에서 대화가 이어지는 자리라면 그게 계속 쌓인다.
 *
 * 그래서 두 가지 그물을 친다 — 물어본 횟수와 전체 시간. 어느 쪽이든 닿으면
 * 스스로 접고 그렇게 알린다. 조용히 멈추면 사용자는 아직 기다리는 줄 안다.
 */

/**
 * 부르는 말.
 *
 * 인식기가 늘 또박또박 돌려주지는 않는다 — "키오브릿지" 를 "키오 브릿지",
 * "키오브리지", "기오브릿지" 로 적어 오는 일이 있다. 띄어쓰기를 지우고 견주며,
 * 실제로 들어 본 어긋남을 여기에 적어 둔다.
 *
 * 짧고 흔한 말은 안 쓴다. "시작" 같은 말은 옆 사람 대화에도 나온다.
 */
const 부르는말 = [
  "키오브릿지", "키오브리지", "키오브릳지", "기오브릿지", "키오부릿지",
  "kiobridge", "keyobridge",
];

/**
 * 두 글자열이 얼마나 다른가(고친 횟수). 같으면 0.
 *
 * 글자 그대로 맞춰 보는 것만으로는 부족하다. 인식기는 "키오브릿찌"·"키오프릿지"
 * 처럼 **한 글자만 어긋난** 답을 자주 내놓는데, 그때마다 표에 적어 넣는 것은
 * 끝이 없다. 한 글자 차이까지는 같은 말로 본다.
 */
const 고친횟수 = (a: string, b: string): number => {
  const 앞줄 = Array.from({ length: b.length + 1 }, (_, i) => i);
  for (let i = 1; i <= a.length; i++) {
    let 왼쪽위 = 앞줄[0];
    앞줄[0] = i;
    for (let j = 1; j <= b.length; j++) {
      const 지금 = 앞줄[j];
      앞줄[j] = Math.min(
        앞줄[j] + 1,                                   // 지우기
        앞줄[j - 1] + 1,                               // 넣기
        왼쪽위 + (a[i - 1] === b[j - 1] ? 0 : 1),       // 바꾸기
      );
      왼쪽위 = 지금;
    }
  }
  return 앞줄[b.length];
};

/**
 * 들은 글이 부르는 말인가. 띄어쓰기와 대소문자는 무시한다.
 *
 * 두 단계로 본다.
 *
 *   ① 글자 그대로 들어 있나. 표에 적어 둔 말들이 여기서 걸린다.
 *   ② 한 글자만 어긋난 토막이 있나. "키오브릿찌" 같은 것을 잡는다.
 *
 * ②의 문턱을 **한 글자**로 둔다. 두 글자까지 열면 여섯 글자짜리 말에서 3분의
 * 1이 달라도 통과한다 — 부르는 말은 앱을 시작시키는 문이라, 옆 사람 대화에
 * 열리면 안 된다. 짧은 말(영어 표기)은 아예 ②를 안 본다. 글자가 적을수록
 * 한 글자 차이가 차지하는 몫이 커지기 때문이다.
 */
export const 불렀나 = (들은말: string): boolean => {
  const 글 = 들은말.toLowerCase().replace(/[\s.,!?~]/g, "");
  if (글 === "") return false;
  if (부르는말.some((말) => 글.includes(말))) return true;

  return 부르는말.some((말) => {
    if (말.length < 5) return false;
    // 말 길이만큼의 창을 밀며 본다. 앞뒤 한 글자가 더 붙거나 빠진 경우까지.
    for (let i = 0; i + 말.length - 1 <= 글.length; i++) {
      for (const 길이 of [말.length - 1, 말.length, 말.length + 1]) {
        const 토막 = 글.slice(i, i + 길이);
        if (토막.length === 0) continue;
        if (고친횟수(토막, 말) <= 1) return true;
      }
    }
    return false;
  });
};

/**
 * 이 브라우저에서 **묻지 않고** 마이크를 열 수 있는가.
 *
 * 여기가 이 기능의 전제다. 브라우저는 처음 한 번은 사람에게 물어야 마이크를
 * 준다 — 그 물음에 답하는 것은 우리 화면이 아니라 브라우저 자신의 창이다.
 * 이미 허용해 둔 자리에서만 상시 대기를 켠다.
 *
 * 아직 안 물어본 자리에서 켜면 두 가지가 나쁘다. 사용자가 아무것도 안 했는데
 * 권한 창이 뜨고, 브라우저에 따라 그 요청이 조용히 막힌다.
 *
 * Permissions API 가 없는 브라우저에서는 false 를 준다 — 모르면 안 켠다.
 */
export const 물어보지않고들을수있나 = async (): Promise<boolean> => {
  try {
    const p = await navigator.permissions?.query({ name: "microphone" as PermissionName });
    return p?.state === "granted";
  } catch {
    return false;
  }
};

/**
 * 마이크가 지금 어떤 상태인가. 화면이 무슨 말을 할지 이걸로 정한다.
 *
 *   됨        이미 허용됐다. 부르는 말을 기다릴 수 있다.
 *   물어봐야함 아직 안 물어봤다. **사람이 누른 자리에서** 한 번 물어야 한다.
 *   막힘      막아 두었다. 우리가 다시 물을 수 없다 — 브라우저 설정에서만 푼다.
 *   모름      Permissions API 가 없다(사파리 등). 물어봐야함 과 같이 다룬다.
 *
 * 모름 을 막힘 으로 치지 않는다. 모른다고 길을 닫으면, 될 수도 있는 기기에서
 * 아무 말 없이 아무것도 안 하게 된다.
 */
export type 마이크상태 = "됨" | "물어봐야함" | "막힘" | "모름";

export const 마이크상태보기 = async (): Promise<마이크상태> => {
  if (!들을수있나()) return "막힘";
  try {
    const p = await navigator.permissions?.query({ name: "microphone" as PermissionName });
    if (!p) return "모름";
    return p.state === "granted" ? "됨" : p.state === "denied" ? "막힘" : "물어봐야함";
  } catch {
    return "모름";
  }
};

/**
 * 마이크를 한 번 열어 브라우저가 묻게 한다. 허락되면 true.
 *
 * **사람이 누른 자리에서만 부른다.** 브라우저는 사용자가 누르지 않은 자리에서
 * 온 요청을 조용히 막는다 — 그러면 물어보지도 못하고 아무 일도 안 일어난다.
 *
 * 연 김에 바로 끈다. 여기서 하려는 일은 녹음이 아니라 허락을 받는 것뿐이다.
 * 안 끄면 마이크 표시등이 켜진 채로 남아, 듣고 있지도 않은데 듣는 것처럼 보인다.
 */
export const 마이크허락받기 = async (): Promise<boolean> => {
  if (!들을수있나()) return false;
  try {
    const 스트림 = await navigator.mediaDevices.getUserMedia({ audio: true });
    스트림.getTracks().forEach((t) => t.stop());
    return true;
  } catch {
    return false;
  }
};

/** 이만큼 물어보고도 못 들으면 접는다. 인식 호출이 끝없이 쌓이지 않게. */
const 최대물어보기 = 12;

/** 이 시간이 지나면 접는다. 말이 아예 없어도 마이크를 계속 열어 두지 않는다. */
const 최대기다림 = 3 * 60 * 1000;

export interface 기다리기 {
  /** 기다리기를 그만둔다. 화면을 떠나거나 사용자가 손으로 시작했을 때. */
  그만기다리기: () => void;
}

/**
 * 부르는 말이 들릴 때까지 기다린다.
 *
 * `들리면` — 부르는 말이 왔다. 한 번만 부르고 스스로 접는다.
 * `그만뒀으면` — 그물에 걸려 접었다. 화면이 "이제 안 듣고 있어요" 로 바꿔야
 *   한다. 조용히 멈추면 사용자는 아직 기다리는 줄 알고 계속 말한다.
 */
export const 부를때까지기다리기 = (
  언어: string,
  { 들리면, 그만뒀으면 }: { 들리면: () => void; 그만뒀으면?: () => void },
): 기다리기 => {
  let 접혔나 = false;
  let 물어본횟수 = 0;
  let 듣던것: { 그만두기: (보내기?: boolean) => void } | null = null;
  const 시작한때 = Date.now();

  const 접기 = (알릴까: boolean) => {
    if (접혔나) return;
    접혔나 = true;
    듣던것?.그만두기(false);
    듣던것 = null;
    if (알릴까) 그만뒀으면?.();
  };

  const 한바퀴 = () => {
    if (접혔나) return;
    if (Date.now() - 시작한때 >= 최대기다림 || 물어본횟수 >= 최대물어보기) { 접기(true); return; }

    듣던것 = 들어보기(언어, (r) => {
      듣던것 = null;
      if (접혔나) return;

      /*
       * 말이 없었다(소리없음). 물어본 것으로 세지 않는다 — 서버에 아무것도 안
       * 보냈기 때문이다. 시간 그물만 남는다.
       */
      if (!("들은말" in r)) {
        // 마이크가 막혔거나 이 기기에서 안 된다. 다시 열어도 같으므로 접는다.
        if (r.못들은이유 === "권한없음" || r.못들은이유 === "안됨") { 접기(true); return; }
        한바퀴();
        return;
      }

      물어본횟수 += 1;
      if (불렀나(r.들은말)) { 접기(false); 들리면(); return; }
      // 우리를 부른 말이 아니다. 무슨 말이었는지는 어디에도 안 남긴다.
      한바퀴();
    }, { 스스로끝내기: true });
  };

  한바퀴();
  return { 그만기다리기: () => 접기(false) };
};

/** 예/아니오를 못 알아들으면 이만큼까지 다시 묻는다. 더 하면 붙잡는 것이 된다. */
const 다시묻기한도 = 3;

/**
 * 화면에 떠 있는 물음에 예/아니오를 말로 받는다.
 *
 * ── 왜 필요한가 ─────────────────────────────────────────────────────────────
 *
 * 동의는 건너뛸 수 없는 관문이다. 그런데 그 관문이 **체크박스**라, 화면을 못
 * 보는 분은 손을 안 대고는 지날 수 없었다. 부르는 말을 알아듣게 만들어 놓고도
 * 그 앞에서 막혀 있던 셈이다.
 *
 * 물음은 화면이 글로 띄운다. 이 함수는 그 글이 다 읽히기를 기다렸다가 답을
 * 듣는다 — 물음을 소리로 따로 만들지 않는 이유는, 화면에 없는 말을 귀로만
 * 들려주면 눈으로 보는 사람과 다른 것을 듣게 되기 때문이다.
 *
 * ── 답하기 전에 목소리가 한 번 나간다 ───────────────────────────────────────
 *
 * 이 앱은 녹음을 서버로 보내 인식한다. 그래서 동의를 말로 받으려면, 동의하기
 * 전에 그 한마디가 서버를 다녀와야 한다 — 순서가 뒤집힌다.
 *
 * 숨기지 않는다. 화면의 물음 문장이 그 사실을 같이 말한다. 그렇게 적어 두고
 * 사용자가 말할지 말지를 고르게 하는 것이, 조용히 받아 두는 것보다 낫다.
 *
 * ── 아니라고 하면 다시 묻지 않는다 ──────────────────────────────────────────
 *
 * '아니오' 는 답이 없는 것이 아니라 답이다. 거기서 또 물으면 붙잡는 것이 된다.
 * 못 알아들었을 때만 다시 묻고, 그것도 세 번까지다.
 */
export const 말로예아니오받기 = (
  언어: string,
  { 네라고하면, 아니라고하면, 그만뒀으면 }: {
    네라고하면: () => void;
    아니라고하면?: () => void;
    그만뒀으면?: () => void;
  },
): 기다리기 => {
  let 접혔나 = false;
  let 못알아들음 = 0;
  let 듣던것: { 그만두기: (보내기?: boolean) => void } | null = null;

  const 접기 = (알릴까: boolean) => {
    if (접혔나) return;
    접혔나 = true;
    듣던것?.그만두기(false);
    듣던것 = null;
    if (알릴까) 그만뒀으면?.();
  };

  const 한바퀴 = () => {
    if (접혔나) return;
    /*
     * 물음이 다 읽히기 전에 마이크를 열면 두 가지가 어긋난다 — 듣기가 읽던
     * 것을 끊어서 무엇을 묻는지 못 듣게 되고, 안 끊더라도 스피커 소리가
     * 녹음에 실린다. 시작기다림 을 주는 이유는 speech.ts 주석에 있다.
     */
    void 다읽을때까지(8000, { 시작기다림: 1500 }).then(() => {
      if (접혔나) return;
      듣던것 = 들어보기(언어, (r) => {
        듣던것 = null;
        if (접혔나) return;

        if (!("들은말" in r)) {
          // 마이크가 막혔거나 이 기기에서 안 된다. 다시 열어도 같다.
          if (r.못들은이유 === "권한없음" || r.못들은이유 === "안됨") { 접기(true); return; }
          못알아들음 += 1;
          if (못알아들음 >= 다시묻기한도) { 접기(true); return; }
          한바퀴();
          return;
        }

        const 답 = 예아니오(r.들은말, 언어 === "en-US");
        if (답 === true) { 접기(false); 네라고하면(); return; }
        // 아니라고 했다. 답을 들은 것이므로 다시 묻지 않는다.
        if (답 === false) { 접기(false); 아니라고하면?.(); return; }

        못알아들음 += 1;
        if (못알아들음 >= 다시묻기한도) { 접기(true); return; }
        한바퀴();
      }, { 스스로끝내기: true });
    });
  };

  한바퀴();
  return { 그만기다리기: () => 접기(false) };
};
