/**
 * 로그인하면 서버가 주는 accessToken.
 *
 * ── 어디에도 적어 두지 않는다 ───────────────────────────────────────────────
 *
 * **메모리에만 둔다.** sessionStorage 에도 안 남긴다.
 *
 * 이 앱은 새로고침을 넘겨 이용을 잇는다(session.ts). 그런데 토큰은 그 규칙에서
 * 빼 둔다 — 적어 두는 순간 개발자 도구를 열 수 있는 사람이 그대로 읽고, 그 값
 * 하나로 남의 주문표를 읽고 지울 수 있다. 비밀번호를 안 남기는 것과 같은
 * 판단이다(session.ts 의 '담지 않는 것').
 *
 * 그래서 새로고침하면 토큰이 사라진다. 계정 자체(userId·loginId)는 남으므로
 * 화면은 로그인한 것처럼 보이는데 서버 요청은 401 을 받는다. **그 상태를 화면이
 * 알아채고 다시 로그인하라고 말해야 한다** — 401 을 받은 자리에서 처리한다.
 *
 * ── 왜 필요해졌나 ───────────────────────────────────────────────────────────
 *
 * 백엔드가 로그인·회원가입 응답에 accessToken 을 넣기 시작했다. 주문표 조회·저장·
 * 삭제는 이제 `Authorization: Bearer {accessToken}` 을 요구한다. 예전에는 경로의
 * userId 만으로 됐는데, 그건 남의 번호를 적으면 남의 것을 볼 수 있다는 뜻이었다.
 */

let 토큰: string | null = null;
/** 서버가 알려 준 만료 시각(ms). 모르면 null 이다. */
let 만료: number | null = null;

export const 접근토큰 = {
  /**
   * 없거나 만료됐으면 null.
   *
   * 만료를 여기서 보는 이유 — 지난 토큰을 붙여 보내면 서버가 401 로 답하고,
   * 사용자는 한 번 실패한 뒤에야 다시 로그인하라는 말을 듣는다. 시각을 알고
   * 있으면 보내기 전에 안다. 서버가 만료를 안 주면 이 검사는 그냥 지나간다.
   */
  읽기(): string | null {
    if (토큰 === null) return null;
    if (만료 !== null && Date.now() >= 만료) { 토큰 = null; 만료 = null; return null; }
    return 토큰;
  },

  /**
   * 로그인·회원가입 응답에서 받은 값을 담는다. 빈 문자열은 없는 것으로 본다.
   *
   * 만료는 서버가 ISO 문자열로 준다(expiresAt). 못 읽으면 안 받는다 — 잘못 읽은
   * 시각으로 멀쩡한 토큰을 버리는 것보다, 모르는 채로 두고 401 을 받는 편이 낫다.
   */
  담기(v: unknown, 만료값?: unknown): void {
    토큰 = typeof v === "string" && v.trim() !== "" ? v : null;
    const t = typeof 만료값 === "string" ? Date.parse(만료값)
      : typeof 만료값 === "number" ? 만료값 : NaN;
    만료 = 토큰 !== null && Number.isFinite(t) ? t : null;
  },

  /** 로그아웃·기기 지우기·401 을 받았을 때 비운다. */
  비우기(): void {
    토큰 = null;
    만료 = null;
  },
};
