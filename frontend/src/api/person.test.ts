import { beforeEach, describe, expect, it } from "vitest";
import { 사람식별자 } from "@/api/person";

// 모듈 저장소라 시험 사이에 값이 남는다.
beforeEach(() => 사람식별자.비우기());

/*
 * 이 파일이 지키는 것: 이 값은 **사람**을 가리킨다.
 *
 * 킷 계약의 CanonicalProfile.profileId 자리에 들어간다. 여태 주문표 id 가
 * 들어가 있었고, 그래서 주문표를 바꿀 때마다 사람이 바뀐 것으로 읽혔다.
 */
describe("게스트", () => {
  it("한 번 만들면 계속 같은 값이다", () => {
    const 첫 = 사람식별자.읽기();
    expect(사람식별자.읽기()).toBe(첫);
    expect(사람식별자.읽기()).toBe(첫);
  });

  it("게스트끼리는 겹치지 않는다", () => {
    const 첫 = 사람식별자.읽기();
    사람식별자.비우기();
    expect(사람식별자.읽기()).not.toBe(첫);
  });

  it("게스트 값임을 앞머리로 알 수 있다", () => {
    // 기록에서 계정 값(u_)과 한눈에 갈려야 한다.
    expect(사람식별자.읽기()).toMatch(/^g_/);
  });
});

describe("로그인한 사람", () => {
  it("계정 번호로 고정된다", () => {
    사람식별자.계정으로(7);
    expect(사람식별자.읽기()).toBe("u_7");
    expect(사람식별자.읽기()).toBe("u_7");
  });

  it("같은 계정이면 기기가 달라도 같은 값이다", () => {
    // 계약의 '오래 유지' 는 이 성질을 말한다.
    사람식별자.계정으로(7);
    const 이기기 = 사람식별자.읽기();
    사람식별자.비우기();
    사람식별자.계정으로(7);
    expect(사람식별자.읽기()).toBe(이기기);
  });

  it("게스트로 쓰다 로그인하면 계정 값으로 바뀐다", () => {
    const 게스트 = 사람식별자.읽기();
    사람식별자.계정으로(7);
    expect(사람식별자.읽기()).not.toBe(게스트);
    expect(사람식별자.읽기()).toBe("u_7");
  });
});

describe("비우기", () => {
  it("로그아웃하면 계정 값이 남지 않는다", () => {
    /*
     * 로그아웃은 이 기기를 다음 사람에게 넘기는 자리이기도 하다. 계정 값을
     * 그대로 두면 다음 사람이 앞사람의 식별자로 주문한다 — 알레르기·가격
     * 한도를 로그아웃에서 비우는 것과 같은 이유다.
     */
    사람식별자.계정으로(7);
    사람식별자.비우기();
    expect(사람식별자.읽기()).not.toBe("u_7");
    expect(사람식별자.읽기()).toMatch(/^g_/);
  });
});

describe("실제 개인정보는 안 담는다", () => {
  it("계정 번호와 난수뿐이다", () => {
    // 킷이 PERSONAL_DATA_NOT_ALLOWED 로 제출 전체를 거절하는 자리다.
    expect(사람식별자.읽기()).toMatch(/^g_[0-9a-z]+$/);
    사람식별자.계정으로(42);
    expect(사람식별자.읽기()).toMatch(/^u_\d+$/);
  });
});
