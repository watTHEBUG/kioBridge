/**
 * 말이 끝났는지를 **기기 안에서** 지켜본다.
 *
 * ── 왜 필요한가 ─────────────────────────────────────────────────────────────
 *
 * 녹음은 말이 끝난 것을 스스로 못 알아챈다(listen.ts). 그래서 지금은 사람이
 * "그만 듣기" 를 눌러야 한 답이 끝난다 — 한 칸에 두 번, 다섯 칸이면 열 번이다.
 *
 * 화면을 못 보는 분에게는 그 열 번이 전부 장벽이다. 어디를 눌러야 하는지
 * 찾는 일이 답하는 일보다 오래 걸린다. 말이 끝난 것을 앱이 알아채면 그 열
 * 번이 사라진다.
 *
 * ── 소리는 밖으로 안 나간다 ─────────────────────────────────────────────────
 *
 * 여기서 보는 것은 **소리의 크기뿐**이다. AnalyserNode 가 브라우저 안에서
 * 파형을 재고, 우리는 그 숫자만 읽는다. 녹음한 소리가 서버로 가는 것은 지금과
 * 똑같이 listen.ts 가 한 번 보낼 때뿐이고, 이 파일은 아무것도 보내지 않는다.
 *
 * AudioWorklet 이 아니라 AnalyserNode 를 쓴다. 둘 다 기기 안에서 돌지만
 * AnalyserNode 는 파일을 따로 두지 않아도 되고, 50ms 마다 한 번 읽는 정도는
 * 본 스레드에서도 가볍다.
 *
 * ── 기기마다 조용한 정도가 다르다 ───────────────────────────────────────────
 *
 * "이 값을 넘으면 말소리" 로 못 박으면 안 된다. 조용한 방과 식당 앞은 바탕
 * 소음이 열 배 넘게 차이 난다 — 못 박은 값은 한쪽에서는 아무 말도 못 듣고
 * 다른 쪽에서는 계속 말하는 중이라고 본다.
 *
 * 그래서 처음 얼마 동안을 재서 그 자리의 바탕 소음을 먼저 잡고, 거기서 얼마나
 * 솟는지로 본다.
 */

/** 얼마나 자주 소리 크기를 읽나. 50ms 면 사람이 말을 멈춘 것을 놓치지 않는다. */
const 재는간격 = 50;

/** 이만큼은 바탕 소음을 재는 데 쓴다. 이 동안의 소리는 말로 세지 않는다. */
const 바탕재는시간 = 400;

/** 바탕 소음보다 이 배수 넘게 솟으면 말소리로 본다. */
const 솟는배수 = 2.2;

/**
 * 아주 조용한 방에서는 바탕이 0에 가까워 배수만으로는 숨소리도 말이 된다.
 * 바닥값을 둔다 — 이보다 작으면 배수와 상관없이 말로 안 본다.
 */
const 최소크기 = 0.012;

/** 말이 이만큼 끊기면 끝난 것으로 본다. 문장 사이 숨 고르기보다는 길게. */
const 끝으로볼무음 = 1200;

/** 말소리가 이만큼 이어져야 '말이 시작됐다' 로 친다. 툭 하는 소리를 거른다. */
const 말로볼길이 = 150;

export interface 말지켜보기결과 {
  /** 지켜보기를 그만둔다. 오디오 자원도 같이 놓는다. */
  그만보기: () => void;
}

/**
 * 스트림에서 말이 끝나는 순간을 알려 준다.
 *
 * `말이끝나면` — 말이 있었고 그 뒤 조용해졌다. 녹음을 끝내면 되는 자리다.
 * `아무말도없으면` — 기다리는 동안 말이 한 번도 없었다. 부르는 쪽이 "안
 *   들렸어요" 로 접을지, 그냥 기다릴지 정한다.
 *
 * 둘 중 하나가 한 번 불리면 더는 안 부른다. 지켜보기도 스스로 접는다.
 */
export const 말끝지켜보기 = (
  스트림: MediaStream,
  { 말이끝나면, 아무말도없으면 }: { 말이끝나면: () => void; 아무말도없으면?: () => void },
  { 기다림 = 8000 }: { 기다림?: number } = {},
): 말지켜보기결과 => {
  const AudioCtx = globalThis.AudioContext
    ?? (globalThis as unknown as { webkitAudioContext?: typeof AudioContext }).webkitAudioContext;
  // 오디오를 못 다루는 브라우저다. 지켜보지 않는다 — 부르는 쪽은 예전처럼
  // 사람이 '그만 듣기' 를 누르는 길과 최대 녹음 시간으로 그대로 돌아간다.
  if (!AudioCtx) return { 그만보기: () => {} };

  let ctx: AudioContext;
  let 분석기: AnalyserNode;
  let 소스: MediaStreamAudioSourceNode;
  try {
    ctx = new AudioCtx();
    분석기 = ctx.createAnalyser();
    분석기.fftSize = 1024;
    소스 = ctx.createMediaStreamSource(스트림);
    소스.connect(분석기);
  } catch {
    return { 그만보기: () => {} };
  }
  /*
   * 사람이 누른 자리가 아니면 오디오가 멈춘 채로 만들어지는 브라우저가 있다.
   * 깨워 둔다 — 실패해도 그냥 둔다. 그러면 크기가 늘 0 이라 '아무 말도 없음'
   * 으로 접히고, 부르는 쪽이 예전 길로 돌아간다.
   */
  void ctx.resume?.().catch(() => {});

  const 칸 = new Uint8Array(분석기.fftSize);
  let 끝났나 = false;
  let 시계: ReturnType<typeof setInterval> | undefined;
  const 바탕표본: number[] = [];
  let 바탕 = 0;
  let 말시작함 = false;
  let 말이어진시간 = 0;
  let 조용한시간 = 0;
  let 지난시간 = 0;

  const 접기 = () => {
    if (끝났나) return;
    끝났나 = true;
    clearInterval(시계);
    try { 소스.disconnect(); } catch { /* 이미 끊겼다 */ }
    // 스트림 자체는 안 끈다 — 그건 녹음하는 쪽(listen.ts)의 것이다.
    void ctx.close?.().catch(() => {});
  };

  /** 지금 이 순간 소리가 얼마나 큰가(RMS). 0 에 가까우면 조용하다. */
  const 지금크기 = (): number => {
    분석기.getByteTimeDomainData(칸);
    let 합 = 0;
    for (let i = 0; i < 칸.length; i++) {
      // 128 이 무음이다. 거기서 얼마나 벗어났는지를 본다.
      const v = (칸[i] - 128) / 128;
      합 += v * v;
    }
    return Math.sqrt(합 / 칸.length);
  };

  시계 = setInterval(() => {
    if (끝났나) return;
    지난시간 += 재는간격;
    const 크기 = 지금크기();

    // ① 처음 얼마 동안은 이 자리의 바탕 소음을 잰다.
    if (지난시간 <= 바탕재는시간) {
      /*
       * 평균이 아니라 **아래쪽 값**을 쓴다.
       *
       * 평균을 쓰면 이 동안 사람이 말을 시작한 경우 그 말소리가 바탕을 밀어
       * 올린다. 그러면 문턱이 실제 목소리보다 높아져 그 뒤로 아무것도 말로
       * 안 잡히고, 기다림이 다 지나 '아무 말도 없음' 으로 접힌다 — 말을 했는데
       * 녹음이 버려진다.
       *
       * 이어 듣기에서는 이게 흔한 자리다. 안내가 끝나자마자 바로 답하는 것이
       * 정상이고, 잇달아 두 번 실패하면 이어 듣기가 꺼진다. 손을 안 쓰는 분은
       * 거기서 흐름이 멎는다.
       *
       * 아래쪽 4분의 1 지점을 쓰면 표본에 말소리가 섞여도 바탕이 안 튄다.
       */
      바탕표본.push(크기);
      const 정렬 = [...바탕표본].sort((a, b) => a - b);
      바탕 = 정렬[Math.floor((정렬.length - 1) * 0.25)];
      return;
    }

    const 말소리인가 = 크기 > Math.max(바탕 * 솟는배수, 최소크기);

    // ② 아직 말이 시작되지 않았다.
    if (!말시작함) {
      말이어진시간 = 말소리인가 ? 말이어진시간 + 재는간격 : 0;
      if (말이어진시간 >= 말로볼길이) { 말시작함 = true; 조용한시간 = 0; return; }
      if (지난시간 >= 기다림) { 접기(); 아무말도없으면?.(); }
      return;
    }

    // ③ 말이 시작됐다. 이제는 조용해지기를 기다린다.
    조용한시간 = 말소리인가 ? 0 : 조용한시간 + 재는간격;
    if (조용한시간 >= 끝으로볼무음) { 접기(); 말이끝나면(); }
  }, 재는간격);

  return { 그만보기: 접기 };
};
