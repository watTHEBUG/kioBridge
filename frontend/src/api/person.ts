/**
 * 이 사람의 가명 식별자.
 *
 * 킷 계약의 `CanonicalProfile.profileId` 자리에 들어간다 — **주문표 id 가 아니라
 * 사람 단위로 유지돼야 하는 값**이다(PROFILE_DATA_DICTIONARY.md).
 *
 * ── 왜 만들었나 ─────────────────────────────────────────────────────────────
 *
 * 여태 주문표 id 를 그대로 넣고 있었다(canonical.ts 의 `profileId: p.id`).
 * 이름이 같아서 자연스러워 보였지만 뜻이 다른 값이다. 두 가지가 어긋났다.
 *
 *   ① 킷이 이 값으로 사람을 세면 **주문표 개수만큼 사람이 있는 것으로 센다.**
 *   ② 한 연결 안에서 주문표를 바꾸면 서버가 "다른 사람이 접속했다" 로 읽는다
 *      (PairingRegistry.bindInput 의 PAIRING_PROFILE_CHANGED).
 *
 * ── 로그인한 사람 ───────────────────────────────────────────────────────────
 *
 * 계정 번호로 고정한다. 기기를 바꿔도 같은 값이라 계약의 "오래 유지" 를 지킨다.
 * 계정은 이어쓰기에서 되살아나므로(App.tsx) 새로고침해도 같은 값이 나온다.
 *
 * ── 게스트 ──────────────────────────────────────────────────────────────────
 *
 * 한 번 만들어 두고 이 페이지가 살아 있는 동안 계속 쓴다.
 *
 * **기기에 안 남긴다.** 창을 닫아도 남는 자리에는 주문표만 적는다(session.ts).
 * 사람을 알아보는 값을 거기 두면 '다음에 와도 같은 사람' 을 앱이 기억한다는
 * 뜻이고, 이 앱은 그걸 안 하기로 했다.
 *
 * 새로고침하면 값이 바뀐다. 그래도 되는 이유 — 연결(pairingId)도 새로고침을
 * 넘어 안 남으므로(P0-2), 되살릴 연결이 없어서 서버가 앞 값과 견줄 일이 없다.
 * 계약이 요구하는 "한 흐름 안에서 안 바뀐다" 는 그대로 지켜진다.
 *
 * ── 실제 개인정보는 안 담는다 ───────────────────────────────────────────────
 *
 * 계정 번호와 난수뿐이다. 이름·전화번호는 여기 안 들어간다 —
 * 킷이 `PERSONAL_DATA_NOT_ALLOWED` 로 제출 전체를 거절하는 자리이기도 하다.
 */

/** 게스트 값. 앞에 g_ 를 붙여 두면 기록에서 계정 값(u_)과 한눈에 갈린다. */
const 새로만들기 = (): string =>
  `g_${Date.now().toString(36)}${Math.random().toString(36).slice(2, 8)}`;

let 값: string | null = null;

export const 사람식별자 = {
  /** 지금 이 사람의 값. 없으면 게스트 값을 하나 만들어 두고 그걸 계속 쓴다. */
  읽기: (): string => (값 ??= 새로만들기()),

  /**
   * 로그인했다. 이제 계정에 묶인다.
   *
   * 이어쓰기에서 계정을 되살릴 때도 부른다 — 새로고침 뒤에 게스트 값으로
   * 돌아가면 같은 사람이 두 사람으로 세어진다.
   */
  계정으로(userId: number): void {
    값 = `u_${userId}`;
  },

  /**
   * 로그아웃·초기화. 다음에 읽으면 **새 게스트 값**이 만들어진다.
   *
   * 계정 값을 그대로 두면 이 기기를 넘겨받은 다음 사람이 앞사람의 식별자로
   * 주문하게 된다 — 알레르기·가격 한도를 로그아웃 때 비우는 것과 같은 이유다.
   */
  비우기(): void {
    값 = null;
  },
};
