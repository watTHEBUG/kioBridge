import { describe, expect, it } from "vitest";
import { EN } from "./en";

/*
 * 이 파일이 지키는 것 — **화면에 새로 나가는 우리말이 표에서 빠지지 않는다.**
 *
 * ── 왜 t() 를 세지 않고 표를 세나 ───────────────────────────────────────────
 *
 * 이 앱은 문장마다 t() 를 두르지 않는다. 화면을 그린 뒤 DOM 을 훑어 한 번에
 * 바꾼다(i18n/apply.ts 머리말에 그 판단이 적혀 있다). 화면에 나가는 우리말이
 * 600줄 가까이 되고 App.tsx 한 파일에 흩어져 있어서, 손으로 두르면 빠뜨리는
 * 자리가 생기고 그 자리는 화면을 열어 보기 전까지 아무도 모르기 때문이다.
 *
 * 그래서 "옮겨졌나" 는 t() 가 붙었는지로 볼 수 없다. **표에 그 문장이 있는지**로
 * 봐야 한다 — 있으면 옮겨지고, 없으면 우리말로 남는다.
 *
 * 실제로 App.tsx 는 이렇게 쓴다(1360행 근처):
 *
 *   못들음 === "권한없음"
 *     ? "마이크를 쓸 수 없어요. 위에서 손으로 골라 주세요."   ← t() 없음
 *     : ...
 *
 * 그리고 그 문장은 이 표에 있다. 이 파일은 그 규칙을 사람 눈 대신 지킨다.
 */

/** 열쇠가 있고, 옮긴 말에 우리말이 안 남았는지. */
const 옮겨지나 = (문장: string) => {
  const 영어 = EN[문장];
  expect(영어, `표에 없음: ${문장}`).toBeTruthy();
  expect(영어, `옮긴 말에 우리말이 남음: ${문장}`).not.toMatch(/[가-힣]/);
};

describe("한 칸씩 말하기 — 되돌아가기와 이어 듣기", () => {
  it("앞 질문 단추와 첫 질문 안내가 표에 있다", () => {
    옮겨지나("앞 질문");
    옮겨지나("여기가 첫 질문이라 더 앞으로는 갈 수 없어요.");
  });

  it("듣는 중 안내 두 줄이 표에 있다", () => {
    // 이어 듣기냐 아니냐로 문장이 갈린다. 한쪽만 넣으면 그 갈래에서만 우리말이 남는다.
    옮겨지나("듣고 있어요. 말씀하신 뒤 \"그만 듣기\"를 눌러 주세요.");
    옮겨지나("듣고 있어요. 말씀이 끝나면 알아서 다음으로 넘어가요.");
  });
});

describe("부르면 시작하기", () => {
  it("듣고 있다는 안내와 그만뒀다는 안내가 표에 있다", () => {
    /*
     * 이 두 줄은 소리로도 읽힌다(data-소리조용 을 안 붙였다). 화면을 못 보는
     * 분에게는 "지금 불러도 된다" 는 유일한 신호라, 영어 화면에서 우리말로
     * 남으면 영어를 쓰는 분에게는 그 신호가 통째로 없는 셈이 된다.
     */
    옮겨지나("부르는 말을 기다리고 있어요. \"키오브릿지\" 라고 말씀하시면 손대지 않고 시작해요.");
    옮겨지나("이제 부르는 말을 듣고 있지 않아요. 아래 \"바로 시작하기\" 를 눌러 주세요.");
  });
});

describe("말로 받는 동의", () => {
  it("물음과 그만둠 안내가 표에 있다", () => {
    /*
     * 이 줄은 체크박스를 못 찾는 분이 지날 수 있는 유일한 문이다. 영어 화면에서
     * 우리말로 남으면 영어를 쓰는 분에게는 그 문이 통째로 없는 셈이 된다.
     */
    옮겨지나("이용에 동의하시겠어요? 동의하시면 \"네\" 라고 말씀해 주세요. 대답은 알아듣기 위해 서버로 한 번 전송됩니다.");
    옮겨지나("잘 못 알아들어서 그만 들을게요. 위 확인란을 눌러 주세요.");
  });

  it("물음이 '서버로 전송' 을 밝힌다", () => {
    /*
     * 동의를 말로 받으려면 그 한마디가 동의 전에 서버를 다녀와야 한다.
     * 순서가 뒤집히는 것을 숨기지 않기로 했다 — 이 문장에서 그 말이 빠지면
     * 사용자는 모르는 채로 말하게 된다.
     */
    const 물음 = "이용에 동의하시겠어요? 동의하시면 \"네\" 라고 말씀해 주세요. 대답은 알아듣기 위해 서버로 한 번 전송됩니다.";
    expect(물음).toContain("서버로");
    expect(EN[물음]).toContain("sent once");
  });
});

describe("마이크를 아직 안 물어본 자리", () => {
  it("허락 안내와 단추, 막힘 안내가 표에 있다", () => {
    /*
     * 여태 이 자리에서 아무것도 안 했다. 처음 오신 분에게는 말로 시작하는 길이
     * 있는지조차 안 보였고, 말을 걸어도 반응이 없었다 — 화면은 멀쩡한데 아무
     * 일도 안 일어나면 사람은 앱이 고장 났다고 여긴다.
     */
    옮겨지나("말로 답하시려면 마이크를 한 번 허락해 주세요. 허락하시면 다음부터는 손대지 않고 시작할 수 있어요.");
    옮겨지나("마이크 허락하기");
    옮겨지나("마이크가 막혀 있어 말로는 답할 수 없어요. 주소창 옆 자물쇠에서 마이크를 허용하시면 됩니다.");
  });

  it("막힘 안내가 어디서 푸는지까지 말한다", () => {
    // "안 됩니다" 만 말하고 끝내면 사용자는 할 수 있는 일이 없다.
    const 막힘 = "마이크가 막혀 있어 말로는 답할 수 없어요. 주소창 옆 자물쇠에서 마이크를 허용하시면 됩니다.";
    expect(막힘).toContain("자물쇠");
    expect(EN[막힘]).toContain("lock icon");
  });
});

describe("첫 화면", () => {
  it("합친 작은 글이 표에 있다", () => {
    // 두 줄을 한 줄로 합치면서 열쇠도 새로 생겼다. 옛 두 줄의 열쇠는 이제
    // 화면에 안 나가지만, 지우지 않는다 — 다른 화면이 쓸 수 있다.
    옮겨지나("가입 없이 바로 쓸 수 있고, 입력한 내용은 이번 한 번만 쓰고 지워집니다");
  });
});

describe("표 자체가 성한가", () => {
  it("자리표시자가 원문과 옮긴 말에서 같다", () => {
    /*
     * tf() 는 원문에 있는 이름으로만 값을 갈아 끼운다. 옮긴 말에 다른 이름이
     * 들어 있으면 그 자리는 영영 안 채워져, 화면에 `{것들}` 이 글자 그대로
     * 뜬다. 빠져 있으면 반대로 값이 통째로 사라진다.
     */
    const 이름들 = (문장: string) => (문장.match(/\{[^}]*\}/g) ?? []).slice().sort();
    const 어긋난것 = Object.entries(EN)
      .filter(([k, v]) => 이름들(k).join("|") !== 이름들(v).join("|"))
      .map(([k, v]) => `${k} → ${v}`);
    expect(어긋난것).toEqual([]);
  });

  it("옮긴 말에 우리말이 섞인 항목이 없다", () => {
    /*
     * 반쯤 옮긴 문장은 안 옮긴 문장보다 나쁘다 — 무엇이 빠졌는지 안 보인다.
     *
     * 자리표시자 이름은 뺀다. `{전체}`·`{것들}` 처럼 우리말로 지어 두었는데,
     * 그건 화면에 안 나가고 tf() 가 값으로 갈아 끼우는 자리다.
     *
     * **원문에 있는 이름만** 뺀다. `{...}` 를 통째로 지우면, 원문에 없던
     * `{한국어}` 같은 것을 옮긴 말에 적어 두어도 이 검사를 지나간다 — 그리고
     * 그건 tf() 가 못 채우므로 영어 화면에 우리말이 그대로 뜬다.
     */
    const 섞인것 = Object.entries(EN)
      .filter(([k, v]) => {
        const 아는이름 = new Set(k.match(/\{[^}]*\}/g) ?? []);
        const 남은말 = v.replace(/\{[^}]*\}/g, (이름) => (아는이름.has(이름) ? "" : 이름));
        return /[가-힣]/.test(남은말);
      })
      .map(([k, v]) => `${k} → ${v}`);
    expect(섞인것).toEqual([]);
  });

  it("빈 값으로 둔 항목이 없다", () => {
    // 빈 값이면 화면에서 그 자리가 통째로 사라진다. 우리말로 남는 것보다 나쁘다.
    const 빈것 = Object.entries(EN).filter(([, v]) => v.trim() === "").map(([k]) => k);
    expect(빈것).toEqual([]);
  });
});
