import type { RecommendationReason } from "../domain/types";
import { t, tf } from "./t";

/**
 * 추천 이유 한 줄을 지금 언어로 조립한다.
 *
 * ── 왜 따로 있나 ────────────────────────────────────────────────────────────
 *
 * 화면 글은 DOM 을 훑으며 통째로 옮긴다(i18n/apply.ts). 그런데 이 줄만은 통째로
 * 옮길 수가 없다. 매번 다른 메뉴 이름과 고른 값이 들어 있어서 표의 열쇠와 정확히
 * 같아지는 일이 없기 때문이다. 그래서 영어로 바꿔도 여기만 우리말로 남았다.
 *
 * ── 세 조각을 따로 다루는 이유 ──────────────────────────────────────────────
 *
 *   메뉴    안 옮긴다. 가게가 붙인 이름이라 옮기면 사용자가 키오스크 화면에서 그
 *           이름을 못 찾는다. 영어를 쓰는 사람도 눌러야 하는 버튼에 적힌 글자는
 *           우리말이다.
 *   문장    서버가 만든 말. 표에 있는 것만 옮는다(en.ts 의 '서버가 주는 이유').
 *   고른값  우리가 아는 말(포장하기·매운맛…). 표에 있으니 그냥 옮긴다.
 *           **지금은 아무도 안 채운다** — 어느 축 얘기인지 계약에 없어서 짐작을
 *           그만두었다(domain/types.ts 의 고른값). 조립은 그대로 두어, 서버가
 *           축 식별자를 주기 시작하면 채우기만 하면 되게 한다.
 *
 * 모르는 문장은 서버가 준 그대로 둔다 — 지어낸 영어를 보여 주는 것보다 낫고,
 * 무엇이 안 옮겨졌는지 화면에서 바로 보인다(t.ts 와 같은 판단이다).
 */

/** 알레르기 제외 문장. `[PEANUT]` 처럼 이름이 앞에 붙어서 표로는 못 잡는다. */
const 알레르기제외 = /^\[([A-Z_]+)\]\s*알레르기와 겹쳐서 제외됐어요\.?$/;

/**
 * 팀 백엔드의 알레르기 제외 문장. 이름이 우리말이고 가운뎃점으로 이어진다 —
 * "땅콩·새우 알레르기와 겹쳐서 제외됐어요." (ChickenStoreExclusionMessages).
 *
 * 위의 대괄호 꼴과 **둘 다** 받는다. 대괄호 꼴은 계약 문서가 보여 준 모양이고,
 * 실측으로는 이 꼴이 온다. 어느 쪽이 오든 영어 화면에 우리말이 남으면 안 된다.
 */
const 우리말알레르기제외 = /^(.+?) 알레르기와 겹쳐서 제외됐어요\.?$/;

/**
 * 프론트가 만드는 차단 제외 문장(api/backend.ts 의 filterCandidates).
 * "맵기이(가) 맞지 않아서 뺐어요" 처럼 축 이름이 끼어 있어 표로는 못 잡는다.
 */
const 축제외 = /^(.+?)이\(가\) 맞지 않아서 뺐어요$/;

/**
 * 서버가 "이 축이 맞았다" 고 말하는 네 문장. 축 이름만 다르고 틀은 같다.
 *
 *   선호하신 이용 방식과 일치하는 메뉴라 우선 추천드립니다.
 *   선호하신 맵기와 맞는 메뉴라 우선 추천드립니다.
 *   선호하신 뼈/순살과 일치하는 메뉴라 우선 추천드립니다.
 *   선호하신 컵 옵션과 일치하는 메뉴라 우선 추천드립니다.
 *
 * 서버는 축마다 한 줄씩 따로 보낸다. 그래서 두 축이 맞으면 같은 메뉴 이름이
 * 두 줄에 걸쳐 되풀이됐다 — 아래 이유묶기() 가 이 틀을 알아보고 한 줄로 합친다.
 */
const 맞은축 = /^선호하신 (.+?)(?:과|와) (?:일치하는|맞는) 메뉴라 우선 추천드립니다\.?$/;

/**
 * 서버 이유 문장이 부르는 축 이름 → 주문표에서 쓰는 축 이름(domain/catalog.tsx).
 *
 * 두 이름이 늘 같지는 않다. 서버는 "뼈/순살"·"컵 옵션" 이라 부르고 주문표는
 * "형태"·"컵" 이다. 여기가 어긋나면 값을 못 찾아 축 이름으로 물러난다 —
 * 틀린 값을 보여 주지는 않는다.
 */
const 주문표축: Record<string, string> = {
  "이용 방식": "이용 방식",
  "맵기": "맵기",
  "뼈/순살": "형태",
  "컵 옵션": "컵",
};

/** 마지막 글자에 받침이 있으면 '과', 없으면 '와'. "맵기과" 가 되면 안 된다. */
const 받침있나 = (말: string): boolean => {
  const 끝 = 말.charCodeAt(말.length - 1);
  if (!(끝 >= 0xac00 && 끝 <= 0xd7a3)) return false;
  return (끝 - 0xac00) % 28 !== 0;
};

/**
 * 우리가 합친 문장. 이름이 가운뎃점으로 이어져 있다 —
 * "선호하신 포장하기·매운맛과 맞는 메뉴라 우선 추천드립니다."
 *
 * 알레르기 문장과 같은 방식이다. 이름만 하나씩 옮기고 틀은 표에서 가져온다.
 * 가운뎃점이 **있을 때만** 걸리게 해서, 서버가 보낸 한 축짜리 문장은 지금처럼
 * 표의 열쇠로 그대로 옮겨지게 둔다.
 */
const 합친축 = /^선호하신 (.+·.+?)(?:과|와) 맞는 메뉴라 우선 추천드립니다\.$/;

const 문장옮기기 = (문장: string): string => {
  const 합침 = 합친축.exec(문장);
  if (합침) {
    /*
     * 우리말에서도 이 길을 지난다. 옮길 것이 없으니 t() 가 이름을 그대로
     * 돌려주고, 표의 우리말 틀이 다시 맞춰져 "선호하신 포장하기, 매운맛과
     * 맞는 메뉴라 우선 추천드립니다." 가 된다.
     */
    const 것들 = 합침[1].split("·").map((이름) => t(이름)).join(", ");
    return 받침있나(것들)
      ? tf("선호하신 {것들}과 맞는 메뉴라 우선 추천드립니다.", { 것들 })
      : tf("선호하신 {것들}와 맞는 메뉴라 우선 추천드립니다.", { 것들 });
  }
  const 겹침 = 알레르기제외.exec(문장);
  if (겹침) return tf("[{알레르기}] 알레르기와 겹쳐서 제외됐어요.", { 알레르기: 겹침[1] });
  const 축겹침 = 축제외.exec(문장);
  // 축 이름만 옮겨 끼운다. 우리말에서는 t() 가 이름을 그대로 돌려주므로
  // 원문이 글자 그대로 다시 만들어진다 — 알레르기 문장과 같은 방식이다.
  if (축겹침) return tf("{축}이(가) 맞지 않아서 뺐어요", { 축: t(축겹침[1]) });
  const 우리말겹침 = 우리말알레르기제외.exec(문장);
  if (우리말겹침) {
    /*
     * 이름을 하나씩 옮기고 가운뎃점은 그대로 둔다. 우리말 화면에서는 t() 가
     * 이름을 그대로 돌려주므로 서버가 준 문장이 글자 그대로 다시 만들어진다 —
     * 서버 문장을 고쳐 쓰지 않는다는 규칙이 지켜진다. 모르는 이름도 그대로
     * 남는다. 지어내지 않는다(t.ts).
     */
    const 이름들 = 우리말겹침[1].split("·").map((이름) => t(이름)).join("·");
    return tf("{알레르기} 알레르기와 겹쳐서 제외됐어요.", { 알레르기: 이름들 });
  }
  return t(문장);
};

/**
 * 한 줄을 지금 언어로 조립한다.
 *
 * 조각을 이어 붙이는 것이 아니라 자리표시자가 있는 한 문장을 옮긴다 — 언어마다
 * 어순이 달라서 토막을 이으면 옮길 수 없는 말이 된다(t.ts).
 */
export const 이유글 = (r: RecommendationReason): string => {
  // 조각이 없으면 완성문을 그대로 본다. 표에 있으면 옮겨지고, 없으면 그대로다.
  const 문장 = 문장옮기기(r.문장 ?? r.text);
  const 값붙은 = r.고른값 ? tf("{글} (고르신 값: {값})", { 글: 문장, 값: t(r.고른값) }) : 문장;
  /*
   * 메뉴 이름도 옮긴다. 원래는 안 옮겼다 — 키오스크 화면과 같아야 사용자가 그
   * 이름을 찾는다. 그런데 영어 화면에 우리말이 하나도 없어야 한다는 쪽으로 정했다.
   * 킷 fixture 의 여덟 이름은 표(en.ts)에 있고, 표에 없는 이름(사용자가 적은 것)은
   * t() 가 그대로 돌려준다 — 지어내지 않는다.
   */
  return r.메뉴 ? tf("{메뉴} — {글}", { 메뉴: t(r.메뉴), 글: 값붙은 }) : 값붙은;
};

/**
 * 같은 메뉴에 대해 여러 축이 맞았다는 줄을 **한 줄로 합친다.**
 *
 * ── 왜 ──────────────────────────────────────────────────────────────────────
 *
 * 서버는 맞은 축마다 한 줄씩 따로 준다. 두 축이 맞으면 화면이 이렇게 됐다.
 *
 *   반영: 포장 전용 닭강정 — 선호하신 이용 방식과 일치하는 메뉴라 우선 추천드립니다.
 *   반영: 포장 전용 닭강정 — 선호하신 맵기와 맞는 메뉴라 우선 추천드립니다.
 *
 * 메뉴 이름과 뒷말이 통째로 되풀이돼서, 두 줄을 다 읽어야 무엇이 다른지 알 수
 * 있다. 큰 글씨로 보는 분에게는 화면 하나를 이것만으로 채운다. 한 줄로 합친다.
 *
 *   반영: 포장 전용 닭강정 — 선호하신 포장하기, 매운맛과 맞는 메뉴라 우선 추천드립니다.
 *
 * ── 축 이름 대신 고르신 값을 쓴다 ───────────────────────────────────────────
 *
 * "이용 방식" 보다 "포장하기" 가 사용자가 실제로 고른 말이다. 짐작이 아니다 —
 * 어느 축인지는 서버 문장에 적혀 있고, 그 축에 무엇을 골랐는지는 주문표에
 * 있다. 둘 다 아는 것만 쓴다. 주문표에 값이 없거나 "상관없음" 이면 축 이름
 * 그대로 둔다.
 *
 * ── 안 건드리는 것 ──────────────────────────────────────────────────────────
 *
 * 한 축만 맞은 줄은 그대로 둔다. 되풀이가 없어서 합칠 것이 없고, 그 문장들은
 * 표에 열쇠가 그대로 있어 지금처럼 옮겨진다. 못 맞춘 조건·제외 이유도 손대지
 * 않는다 — 저마다 다른 말이라 합치면 뜻이 뭉개진다.
 */
export const 이유묶기 = (
  reasons: RecommendationReason[],
  고른것: Record<string, string[]> = {},
): RecommendationReason[] => {
  const 축찾기 = (r: RecommendationReason): string | undefined =>
    r.kind === "used" ? 맞은축.exec(r.문장 ?? r.text)?.[1] : undefined;

  const 부를이름 = (축: string): string => {
    const 값 = (고른것[주문표축[축] ?? 축] ?? []).filter((v) => v !== "상관없음");
    return 값.length > 0 ? 값.join("·") : 축;
  };

  // 메뉴별로 몇 축이 맞았는지 먼저 센다. 둘 이상일 때만 합친다.
  const 메뉴별 = new Map<string, string[]>();
  for (const r of reasons) {
    const 축 = 축찾기(r);
    if (!축) continue;
    const 열쇠 = r.메뉴 ?? "";
    메뉴별.set(열쇠, [...(메뉴별.get(열쇠) ?? []), 부를이름(축)]);
  }

  const 합친것 = new Set<string>();
  const 나온것: RecommendationReason[] = [];
  for (const r of reasons) {
    const 축 = 축찾기(r);
    if (!축) { 나온것.push(r); continue; }
    const 열쇠 = r.메뉴 ?? "";
    const 것들 = 메뉴별.get(열쇠) ?? [];
    if (것들.length < 2) { 나온것.push(r); continue; }
    // 두 번째부터는 첫 줄에 합쳐졌다. 자리는 첫 줄이 지킨다.
    if (합친것.has(열쇠)) continue;
    합친것.add(열쇠);
    const 목록 = 것들.join("·");
    const 문장 = `선호하신 ${목록}${받침있나(목록) ? "과" : "와"} 맞는 메뉴라 우선 추천드립니다.`;
    // text 도 같이 고친다. 화면이 이걸 목록 열쇠로 쓰고, 합치기 전 문장이
    // 남아 있으면 열쇠가 사라진 줄을 가리킨다.
    나온것.push({ ...r, 문장, text: r.메뉴 ? `${r.메뉴} — ${문장}` : 문장 });
  }
  return 나온것;
};
