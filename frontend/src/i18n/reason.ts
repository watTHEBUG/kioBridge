import type { RecommendationReason } from "../domain/types";
import { t, tf } from "./t";

/**
 * 추천 이유 한 줄을 지금 언어로 조립한다.
 *
 * ── 왜 따로 있나 ────────────────────────────────────────────────────────────
 *
 * 화면 글은 DOM 을 훑으며 통째로 옮긴다(i18n/apply.ts). 그런데 이 줄만은 통째로
 * 옮길 수가 없다. 매번 다른 메뉴 이름과 고른 값이 들어 있어서 표의 열쇠와 정확히
 * 같아지는 일이 없기 때문이다. 그래서 영어로 바꿔도 여기만 우리말로 남았다.
 *
 * ── 세 조각을 따로 다루는 이유 ──────────────────────────────────────────────
 *
 *   메뉴    안 옮긴다. 가게가 붙인 이름이라 옮기면 사용자가 키오스크 화면에서 그
 *           이름을 못 찾는다. 영어를 쓰는 사람도 눌러야 하는 버튼에 적힌 글자는
 *           우리말이다.
 *   문장    서버가 만든 말. 표에 있는 것만 옮는다(en.ts 의 '서버가 주는 이유').
 *   고른값  우리가 아는 말(포장하기·매운맛…). 표에 있으니 그냥 옮긴다.
 *           **지금은 아무도 안 채운다** — 어느 축 얘기인지 계약에 없어서 짐작을
 *           그만두었다(domain/types.ts 의 고른값). 조립은 그대로 두어, 서버가
 *           축 식별자를 주기 시작하면 채우기만 하면 되게 한다.
 *
 * 모르는 문장은 서버가 준 그대로 둔다 — 지어낸 영어를 보여 주는 것보다 낫고,
 * 무엇이 안 옮겨졌는지 화면에서 바로 보인다(t.ts 와 같은 판단이다).
 */

/** 알레르기 제외 문장. `[PEANUT]` 처럼 이름이 앞에 붙어서 표로는 못 잡는다. */
const 알레르기제외 = /^\[([A-Z_]+)\]\s*알레르기와 겹쳐서 제외됐어요\.?$/;

/**
 * 팀 백엔드의 알레르기 제외 문장. 이름이 우리말이고 가운뎃점으로 이어진다 —
 * "땅콩·새우 알레르기와 겹쳐서 제외됐어요." (ChickenStoreExclusionMessages).
 *
 * 위의 대괄호 꼴과 **둘 다** 받는다. 대괄호 꼴은 계약 문서가 보여 준 모양이고,
 * 실측으로는 이 꼴이 온다. 어느 쪽이 오든 영어 화면에 우리말이 남으면 안 된다.
 */
const 우리말알레르기제외 = /^(.+?) 알레르기와 겹쳐서 제외됐어요\.?$/;

/**
 * 프론트가 만드는 차단 제외 문장(api/backend.ts 의 filterCandidates).
 * "맵기이(가) 맞지 않아서 뺐어요" 처럼 축 이름이 끼어 있어 표로는 못 잡는다.
 */
const 축제외 = /^(.+?)이\(가\) 맞지 않아서 뺐어요$/;

const 문장옮기기 = (문장: string): string => {
  const 겹침 = 알레르기제외.exec(문장);
  if (겹침) return tf("[{알레르기}] 알레르기와 겹쳐서 제외됐어요.", { 알레르기: 겹침[1] });
  const 축겹침 = 축제외.exec(문장);
  // 축 이름만 옮겨 끼운다. 우리말에서는 t() 가 이름을 그대로 돌려주므로
  // 원문이 글자 그대로 다시 만들어진다 — 알레르기 문장과 같은 방식이다.
  if (축겹침) return tf("{축}이(가) 맞지 않아서 뺐어요", { 축: t(축겹침[1]) });
  const 우리말겹침 = 우리말알레르기제외.exec(문장);
  if (우리말겹침) {
    /*
     * 이름을 하나씩 옮기고 가운뎃점은 그대로 둔다. 우리말 화면에서는 t() 가
     * 이름을 그대로 돌려주므로 서버가 준 문장이 글자 그대로 다시 만들어진다 —
     * 서버 문장을 고쳐 쓰지 않는다는 규칙이 지켜진다. 모르는 이름도 그대로
     * 남는다. 지어내지 않는다(t.ts).
     */
    const 이름들 = 우리말겹침[1].split("·").map((이름) => t(이름)).join("·");
    return tf("{알레르기} 알레르기와 겹쳐서 제외됐어요.", { 알레르기: 이름들 });
  }
  return t(문장);
};

/**
 * 한 줄을 지금 언어로 조립한다.
 *
 * 조각을 이어 붙이는 것이 아니라 자리표시자가 있는 한 문장을 옮긴다 — 언어마다
 * 어순이 달라서 토막을 이으면 옮길 수 없는 말이 된다(t.ts).
 */
export const 이유글 = (r: RecommendationReason): string => {
  // 조각이 없으면 완성문을 그대로 본다. 표에 있으면 옮겨지고, 없으면 그대로다.
  const 문장 = 문장옮기기(r.문장 ?? r.text);
  const 값붙은 = r.고른값 ? tf("{글} (고르신 값: {값})", { 글: 문장, 값: t(r.고른값) }) : 문장;
  /*
   * 메뉴 이름도 옮긴다. 원래는 안 옮겼다 — 키오스크 화면과 같아야 사용자가 그
   * 이름을 찾는다. 그런데 영어 화면에 우리말이 하나도 없어야 한다는 쪽으로 정했다.
   * 킷 fixture 의 여덟 이름은 표(en.ts)에 있고, 표에 없는 이름(사용자가 적은 것)은
   * t() 가 그대로 돌려준다 — 지어내지 않는다.
   */
  return r.메뉴 ? tf("{메뉴} — {글}", { 메뉴: t(r.메뉴), 글: 값붙은 }) : 값붙은;
};
