import { afterEach, describe, expect, it } from "vitest";
import { 이유글, 이유묶기 } from "./reason";
import { 접근성설정 } from "../api/a11y";
import type { RecommendationReason } from "../domain/types";

/*
 * 이 파일이 지키는 것 — **영어로 바꾸면 이 줄에 우리말이 안 남는다.**
 *
 * 화면 글은 DOM 을 훑으며 통째로 옮기는데(i18n/apply.ts) 이 줄만은 매번 달라서
 * 표의 열쇠와 같아지지 않는다. 그래서 여기만 우리말로 남아 있었다.
 */

const 영어로 = () => 접근성설정.바꾸기({ language: "en-US" });
afterEach(() => 접근성설정.바꾸기({ language: "ko-KR" }));

const 이유 = (조각: Partial<RecommendationReason> & { text: string }): RecommendationReason =>
  ({ kind: "used", ...조각 }) as RecommendationReason;

describe("이유글", () => {
  it("우리말일 때는 서버가 준 그대로다", () => {
    const r = 이유({ text: "x", 문장: "선호하신 맵기와 맞는 메뉴라" });
    expect(이유글(r)).toBe("선호하신 맵기와 맞는 메뉴라");
  });

  it("영어로 바꾸면 우리말이 안 남는다", () => {
    영어로();
    const r = 이유({ text: "x", 문장: "선호하신 맵기와 맞는 메뉴라", 고른값: "매운맛" });
    expect(이유글(r)).not.toMatch(/[가-힣]/);
  });

  it("킷 후보 이름은 옮긴다 — 영어 화면에 우리말이 안 남는다", () => {
    /*
     * 원래는 안 옮겼다(키오스크 화면과 같아야 찾는다). 영어 화면에 우리말이
     * 하나도 없어야 한다는 쪽으로 정해서, 킷 fixture 의 여덟 이름은 표로 옮긴다.
     */
    영어로();
    const r = 이유({ text: "x", 메뉴: "품절 닭강정", 문장: "지금은 품절이라 제외됐어요." });
    expect(이유글(r)).toContain("Sold-out dakgangjeong");
    expect(이유글(r)).not.toMatch(/[가-힣]/);
  });

  it("표에 없는 메뉴 이름은 지어내지 않고 그대로 둔다", () => {
    // 사용자가 적은 이름일 수 있다. t() 의 원칙 그대로 — 모르는 것은 안 바꾼다.
    영어로();
    const r = 이유({ text: "x", 메뉴: "우리집 특제 닭강정", 문장: "지금은 품절이라 제외됐어요." });
    expect(이유글(r)).toContain("우리집 특제 닭강정");
  });

  it("백엔드 실측 추천 이유가 전부 옮겨진다", () => {
    // RecommendationEngineService 의 상수 그대로다. 하나라도 표에서 빠지면
    // 영어 화면에 우리말 이유가 남는다 — 실제로 그랬다(#추천 이유 잔존).
    영어로();
    for (const 문장 of [
      "조건에 맞는 메뉴를 찾지 못해 추천드릴 항목이 없습니다.",
      "선호하신 이용 방식과 일치하는 메뉴라 우선 추천드립니다.",
      "선호하신 맵기와 맞는 메뉴라 우선 추천드립니다.",
      "선호하신 뼈/순살과 일치하는 메뉴라 우선 추천드립니다.",
      "선호하신 컵 옵션과 일치하는 메뉴라 우선 추천드립니다.",
      "남은 후보 중 조건에 가장 가까운 메뉴라 추천드립니다.",
      "일부 정보의 확신도가 낮아 다시 확인이 필요합니다.",
      "지금 시간대가 붐벼서, 매장에서 기다리지 않고 바로 받으실 수 있는 포장 메뉴를 먼저 보여드립니다.",
      "선호하신 이용 방식과 다릅니다.",
      "선호하신 맵기와 다릅니다.",
      "선호하신 뼈/순살과 다릅니다.",
      "선호하신 컵 옵션과 다릅니다.",
    ]) {
      expect(이유글(이유({ text: "x", 문장 }))).not.toMatch(/[가-힣]/);
    }
  });

  it("알레르기 이름이 앞에 붙은 문장도 옮긴다", () => {
    영어로();
    const r = 이유({ text: "x", 문장: "[PEANUT] 알레르기와 겹쳐서 제외됐어요." });
    expect(이유글(r)).toContain("PEANUT");
    expect(이유글(r)).not.toMatch(/[가-힣]/);
  });

  it("팀 백엔드의 우리말 알레르기 문장도 옮긴다 — 실측 형식", () => {
    /*
     * 백엔드는 "[PEANUT]" 이 아니라 "땅콩·새우" 처럼 우리말 이름을 가운뎃점으로
     * 이어 보낸다(ChickenStoreExclusionMessages). 대괄호 꼴만 받으면 이 문장이
     * 표에도 정규식에도 안 걸려서 영어 화면에 우리말이 그대로 남는다(#101 리뷰).
     */
    영어로();
    const r = 이유({ text: "x", 문장: "땅콩·새우 알레르기와 겹쳐서 제외됐어요." });
    expect(이유글(r)).toContain("Peanut");
    expect(이유글(r)).toContain("Shrimp");
    expect(이유글(r)).not.toMatch(/[가-힣]/);
  });

  it("우리말 화면에서는 백엔드 알레르기 문장이 글자 그대로다", () => {
    // 이름을 옮겨 끼워도 우리말에서는 서버가 준 문장이 그대로 다시 만들어져야
    // 한다. 여기가 깨지면 서버 문장을 우리가 고쳐 쓴 것이다.
    const r = 이유({ text: "x", 문장: "땅콩·새우 알레르기와 겹쳐서 제외됐어요." });
    expect(이유글(r)).toBe("땅콩·새우 알레르기와 겹쳐서 제외됐어요.");
  });

  it("백엔드가 달걀이라 불러도 옮긴다", () => {
    // 프론트 목록은 '계란', 백엔드 이름표는 '달걀' 이다. 오는 그대로 받는다.
    영어로();
    const r = 이유({ text: "x", 문장: "달걀 알레르기와 겹쳐서 제외됐어요." });
    expect(이유글(r)).toContain("Egg");
    expect(이유글(r)).not.toMatch(/[가-힣]/);
  });

  it("프론트가 만드는 제외 문장도 옮겨진다 — 축 이름이 끼어도", () => {
    /*
     * 품절·차단 후보의 제외 문장은 프론트가 직접 만든다(api/backend.ts 의
     * filterCandidates). 메뉴 이름은 menuName 으로 따로 나르므로 문장은 고정문
     * 아니면 축 이름이 끼인 꼴 하나다. 축 꼴이 표에 안 걸리면 영어 화면에
     * 우리말이 남는다(#101 리뷰).
     */
    영어로();
    expect(이유글(이유({ text: "x", 문장: "지금 팔지 않아서 뺐어요" }))).not.toMatch(/[가-힣]/);
    expect(이유글(이유({ text: "x", 문장: "조건에 맞지 않아서 뺐어요" }))).not.toMatch(/[가-힣]/);
    const 축꼴 = 이유글(이유({ text: "x", 문장: "맵기이(가) 맞지 않아서 뺐어요" }));
    expect(축꼴).toContain("Spice level");
    expect(축꼴).not.toMatch(/[가-힣]/);
  });

  it("우리말 화면에서는 축 문장이 글자 그대로다", () => {
    const r = 이유({ text: "x", 문장: "컵이(가) 맞지 않아서 뺐어요" });
    expect(이유글(r)).toBe("컵이(가) 맞지 않아서 뺐어요");
  });

  it("백엔드의 고정 제외 문장 넷이 전부 옮겨진다", () => {
    // 마침표까지가 키다. 하나라도 표에서 빠지면 영어 화면에 우리말이 남는다.
    영어로();
    for (const 문장 of [
      "지금은 품절이라 제외됐어요.",
      "설정하신 가격 한도를 넘어서 제외됐어요.",
      "알레르기 조건과 겹쳐서 제외됐어요.",
      "선택하신 조건과 맞지 않아 제외됐어요.",
    ]) {
      expect(이유글(이유({ text: "x", 문장 }))).not.toMatch(/[가-힣]/);
    }
  });

  it("모르는 문장은 지어내지 않고 서버가 준 그대로 둔다", () => {
    // 서버가 새 문장을 만들면 그 줄은 우리말로 보인다. 지어낸 영어보다 낫고,
    // 무엇이 안 옮겨졌는지 화면에서 바로 보인다(t.ts 와 같은 판단).
    영어로();
    const r = 이유({ text: "x", 문장: "서버가 오늘 처음 만든 문장이에요" });
    expect(이유글(r)).toBe("서버가 오늘 처음 만든 문장이에요");
  });

  it("조각이 없으면 완성문을 그대로 쓴다", () => {
    const r = 이유({ text: "이어 붙여 둔 완성문" });
    expect(이유글(r)).toBe("이어 붙여 둔 완성문");
  });
});

/*
 * 서버는 맞은 축마다 한 줄씩 따로 준다. 두 축이 맞으면 화면이 이렇게 됐다.
 *
 *   반영: 포장 전용 닭강정 — 선호하신 이용 방식과 일치하는 메뉴라 우선 추천드립니다.
 *   반영: 포장 전용 닭강정 — 선호하신 맵기와 맞는 메뉴라 우선 추천드립니다.
 *
 * 메뉴 이름과 뒷말이 통째로 되풀이돼서, 두 줄을 다 읽어야 무엇이 다른지 알 수
 * 있다. 한 줄로 합치고, 축 이름 대신 사용자가 고른 값으로 부른다.
 */
describe("이유묶기", () => {
  const 맞음 = (메뉴: string, 문장: string): RecommendationReason =>
    ({ kind: "used", text: `${메뉴} — ${문장}`, 메뉴, 문장 }) as RecommendationReason;

  const 이용방식 = "선호하신 이용 방식과 일치하는 메뉴라 우선 추천드립니다.";
  const 맵기 = "선호하신 맵기와 맞는 메뉴라 우선 추천드립니다.";
  const 형태 = "선호하신 뼈/순살과 일치하는 메뉴라 우선 추천드립니다.";

  const 주문표 = { "이용 방식": ["포장하기"], "맵기": ["매운맛"], "형태": ["순살"] };

  it("같은 메뉴의 두 줄을 한 줄로 합치고, 고르신 값으로 부른다", () => {
    const 합침 = 이유묶기([맞음("포장 전용 닭강정", 이용방식), 맞음("포장 전용 닭강정", 맵기)], 주문표);
    expect(합침).toHaveLength(1);
    expect(이유글(합침[0])).toBe(
      "포장 전용 닭강정 — 선호하신 포장하기, 매운맛과 맞는 메뉴라 우선 추천드립니다.",
    );
  });

  it("조사를 마지막 값에 맞춘다 — '맵기과' 가 되면 안 된다", () => {
    // 끝이 '기'(받침 없음)면 '와', '맛'(받침 있음)이면 '과'.
    const 순서바꿈 = 이유묶기([맞음("A", 맵기), 맞음("A", 이용방식)], 주문표);
    expect(이유글(순서바꿈[0])).toContain("매운맛, 포장하기와 맞는");
  });

  it("주문표에 값이 없으면 축 이름 그대로 둔다 — 지어내지 않는다", () => {
    const 합침 = 이유묶기([맞음("A", 이용방식), 맞음("A", 맵기)], {});
    expect(이유글(합침[0])).toBe("A — 선호하신 이용 방식, 맵기와 맞는 메뉴라 우선 추천드립니다.");
  });

  it("'상관없음' 은 값으로 안 쓴다 — 축 이름이 더 알려 준다", () => {
    const 합침 = 이유묶기([맞음("A", 이용방식), 맞음("A", 맵기)], { "이용 방식": ["상관없음"], "맵기": ["매운맛"] });
    expect(이유글(합침[0])).toContain("이용 방식, 매운맛과");
  });

  it("서버 축 이름이 주문표와 달라도 값을 찾는다 — 뼈/순살은 '형태' 다", () => {
    const 합침 = 이유묶기([맞음("A", 형태), 맞음("A", 맵기)], 주문표);
    expect(이유글(합침[0])).toContain("순살, 매운맛과");
  });

  it("한 축만 맞은 줄은 손대지 않는다", () => {
    // 되풀이가 없어 합칠 것이 없고, 이 문장은 표에 열쇠가 그대로 있다.
    const 그대로 = 이유묶기([맞음("A", 맵기)], 주문표);
    expect(그대로).toHaveLength(1);
    expect(이유글(그대로[0])).toBe("A — 선호하신 맵기와 맞는 메뉴라 우선 추천드립니다.");
  });

  it("같은 축이 두 번 와도 한 번만 센다 — '매운맛·매운맛' 이 되면 안 된다", () => {
    /*
     * 서버는 축마다 한 줄씩 주지만 겹쳐 온 적이 있는 자리다. 그대로 세면
     * 같은 조건을 두 번 말하는 줄이 되어, 합치지 않느니만 못하다.
     * 축이 하나뿐이므로 합치지 않고 첫 줄을 그대로 둔다.
     */
    const 겹침 = 이유묶기([맞음("A", 맵기), 맞음("A", 맵기)], 주문표);
    expect(이유글(겹침[0])).not.toContain("매운맛, 매운맛");
    expect(겹침).toHaveLength(2);
    expect(이유글(겹침[0])).toBe("A — 선호하신 맵기와 맞는 메뉴라 우선 추천드립니다.");
  });

  it("겹친 축이 있어도 서로 다른 축이 둘이면 합친다", () => {
    const 합침 = 이유묶기([맞음("A", 맵기), 맞음("A", 맵기), 맞음("A", 이용방식)], 주문표);
    /*
     * 길이를 먼저 본다. 첫 문장만 맞게 만들고 겹친 줄을 둘째 항목으로 남겨도
     * [0] 검사만으로는 통과한다 — 화면에는 같은 말이 한 줄 더 붙는데도.
     */
    expect(합침).toHaveLength(1);
    expect(이유글(합침[0])).toBe("A — 선호하신 매운맛, 포장하기와 맞는 메뉴라 우선 추천드립니다.");
  });

  it("메뉴가 다르면 안 합친다", () => {
    const 둘 = 이유묶기([맞음("A", 이용방식), 맞음("B", 맵기)], 주문표);
    expect(둘).toHaveLength(2);
  });

  it("못 맞춘 것과 뺀 것은 건드리지 않는다", () => {
    const 원래 = [
      { kind: "unmet", text: "x", 문장: "선호하신 맵기와 다릅니다." },
      { kind: "excluded", text: "y", 문장: "지금은 품절이라 제외됐어요." },
    ] as RecommendationReason[];
    expect(이유묶기(원래, 주문표)).toEqual(원래);
  });

  it("합친 자리는 첫 줄 자리를 지킨다", () => {
    const 못맞춤 = { kind: "unmet", text: "z", 문장: "선호하신 컵 옵션과 다릅니다." } as RecommendationReason;
    const 나온것 = 이유묶기([맞음("A", 이용방식), 못맞춤, 맞음("A", 맵기)], 주문표);
    expect(나온것).toHaveLength(2);
    expect(나온것[1]).toBe(못맞춤);
  });

  it("합친 줄도 영어로 바꾸면 우리말이 안 남는다", () => {
    영어로();
    const 합침 = 이유묶기([맞음("포장 전용 닭강정", 이용방식), 맞음("포장 전용 닭강정", 맵기)], 주문표);
    const 글 = 이유글(합침[0]);
    expect(글).not.toMatch(/[가-힣]/);
    // 값 이름도 옮겨져야 한다. 틀만 영어면 "Takeout-only ... 포장하기" 가 남는다.
    // 표(en.ts)가 쓰는 말 그대로다 — 포장하기는 "Take out", 매운맛은 "Hot".
    expect(글).toContain("Take out");
    expect(글).toContain("Hot");
  });

  it("text 도 같이 고친다 — 화면이 이걸 목록 열쇠로 쓴다", () => {
    // 합치기 전 문장이 text 에 남으면, 열쇠가 사라진 줄을 가리킨다.
    const 합침 = 이유묶기([맞음("A", 이용방식), 맞음("A", 맵기)], 주문표);
    expect(합침[0].text).toBe("A — 선호하신 포장하기·매운맛과 맞는 메뉴라 우선 추천드립니다.");
  });
});
